/**
 * Часы ленда: физическая подсказка для логических меток
 * ([docs/04 §3](../../../../docs/04-crdt-core.md#3-lww)).
 *
 * Вынесены из `replica.ts` отдельным модулем, потому что читателей стало двое:
 * старая `Replica` (оракул дифференциальных тестов) и боевой `Land`. Общая
 * реализация здесь не роскошь, а требование корректности — детерминированные
 * часы обязаны быть ОДНИМИ на обе стороны сверки, иначе метки времени разойдутся
 * и сверка начнёт мерить разницу часов, а не разницу раскладок.
 */

/** Источник физической подсказки для логических часов. В тестах — детерминированный. */
export interface Clock {
  now(): number
}

/** Часы, которые двигаются только руками теста. */
export interface FixedClock extends Clock {
  advance(delta: number): void
}

/**
 * Детерминированные часы: стоят, пока тест не сдвинет их сам.
 *
 * Общий экземпляр на несколько реплик моделирует «настенное время»: правки,
 * сделанные без `advance`, попадают в одну секунду и разводятся уже арбитром
 * по `peer` — самый интересный для LWW случай.
 *
 * @example
 * ```ts
 * const clock = fixedClock(1000)
 * const land = new Land(peer, clock)
 * clock.advance(1)   // следующая запись перекроет предыдущие по времени
 * ```
 */
export function fixedClock(start: number): FixedClock {
  let time = start
  return {
    now: () => time,
    advance: (delta: number) => { time += delta },
  }
}

/** `tick` — два байта (docs/03 §2). Больше в юнит просто не записать. */
const TICK_MAX = 0xffff

/**
 * Логическая метка ленда — порт `$giper_baza_face_map.tick()`.
 *
 * Пара `(time, tick)` у одного пира строго растёт при каждой записи, и на этом
 * держится строгость арбитража: `cmpAt` отдаёт ноль только для юнитов одного
 * поста. Метка не меньше ни физической подсказки, ни максимума, увиденного в
 * сети.
 *
 * Все поля объявлены в конструкторе — один шейп (правило 2 горячего пути).
 */
export class Stamp {
  /** Секунды последней нашей записи. */
  time: number
  /** Шаг внутри секунды у последней нашей записи. */
  tick: number
  /** Максимум времени, увиденный в сети: не даёт часам отстать от собеседников. */
  heard: number
  heardTick: number
  /**
   * Секунда, в которую в последний раз писал ЧУЖОЙ пир.
   *
   * Именно секунда, а не флаг «чей был максимум» (порт `_peer_last` из baza).
   * Флаг обновлялся только под строго новую метку, поэтому чужой юнит с меткой
   * НЕ БОЛЬШЕ уже записанного максимума терялся для часов целиком: наша
   * следующая запись оставалась в той же секунде, где арбитром становится
   * `peer ↑`, и причинно поздняя правка проигрывала той, которую сама только
   * что увидела. Воспроизведение — `regressions/causal-write-loses-to-heard`.
   */
  other: number

  constructor() {
    this.time = 0
    this.tick = 0
    this.heard = 0
    this.heardTick = 0
    this.other = 0
  }

  /**
   * Услышать чужую (или свою) метку. Зовётся и под ОТВЕРГНУТЫЙ юнит: важен сам
   * факт, что такое время в сети уже видели, иначе наша следующая запись
   * проиграет LWW тому, что уже доехало.
   */
  hear(time: number, tick: number, mine: boolean): void {
    if (time > this.heard || (time === this.heard && tick > this.heardTick)) {
      this.heard = time
      this.heardTick = tick
    }
    if (!mine && time > this.other) this.other = time
  }

  /**
   * Метка для новой локальной записи.
   *
   * Три ветки, и средняя — самая важная: если в эту секунду уже писал ДРУГОЙ
   * пир, время сдвигается на секунду вперёд. Без неё причинно поздняя запись
   * проигрывает уже услышанной — в пределах одной секунды арбитром становится
   * `peer`, и надгробие от `p2` не может перебить юнит от `p1`, хотя создано
   * строго после его доставки. Наивное `max(now, heard)` дыру не закрывает.
   */
  next(now: number): void {
    const seen = this.heard > this.time ? this.heard : this.time

    if (seen < now) {
      this.time = now
      this.tick = 0
    } else if (this.other >= seen) {
      this.time = seen + 1
      this.tick = 0
    } else {
      this.time = seen
      this.tick = (this.tick > this.heardTick ? this.tick : this.heardTick) + 1
      // Переполнение `tick` молча обрезалось бы при записи в два байта, пара
      // `(time, tick)` перестала бы строго расти, и запись проиграла бы
      // собственной предыдущей. Поймал это не тест, а строка бенча
      // `invalidate/recomputed 0` в прототипе — секунда вперёд дешевле.
      if (this.tick > TICK_MAX) {
        this.time = seen + 1
        this.tick = 0
      }
    }
  }
}
