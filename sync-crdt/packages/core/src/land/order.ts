//
// Порт `sand_ordered` из baza делался ради скорости — и по замеру
// (`bench/budgets.json`) выигрыш есть только на append-only списке. Как только в
// наборе появляются надгробия или перемещения, однопроходная раскладка проигрывает
// группировке из `order-naive.ts` в 1.16–1.62 раза. Держим её как независимую
// вторую реализацию: 82 теста проходят через обе, и расхождений на ~89 000
// сверенных состояний не найдено.

import { compare } from './lww'
import { ROOT, type Sand } from './sand'

/**
 * Звено раскладки. Один узел графа — одно звено; список односвязный, потому что
 * вставка всегда происходит **за уже известным** звеном, а назад никто не ходит.
 *
 * `sand === null` ровно у одного звена — стража, который изображает {@link ROOT}.
 * Страж лежит в общей карте под ключом {@link ROOT}, поэтому поиск места для
 * `lead === ROOT` не отличается от любого другого и не требует ветки.
 */
interface Slot {
  /** Ключ звена. У стража — {@link ROOT}. */
  readonly self: string
  /** Юнит звена. `null` только у стража. */
  readonly sand: Sand | null
  next: Slot | null
}

/**
 * Полный порядок на юнитах: {@link compare}, а при полном совпадении меток —
 * арбитр по `self`.
 *
 * `compare` отдаёт ноль только для юнитов одного поста, то есть для одного и
 * того же `self`; после свёртки такие в наборе не встречаются. Значит арбитр
 * срабатывает лишь на входах, собранных руками мимо `Replica`, — и нужен он не
 * для них, а чтобы порядок раскладки **вообще не зависел** от порядка перебора
 * входного массива. Стабильная сортировка на ничьих сохранила бы порядок
 * поступления, и две реплики с одним набором юнитов прочитали бы разное.
 */
function rank(a: Sand, b: Sand): number {
  const lww = compare(a, b)
  if (lww !== 0) return lww
  if (a.self === b.self) return 0
  return a.self < b.self ? -1 : 1
}

/**
 * Порядок чтения внутри одного `head` — порт `sand_ordered` из baza
 * ([land/land.ts:712](../../../../../baza/land/land.ts)).
 *
 * Однопроходная раскладка в связный список вместо обхода дерева: юниты
 * разбираются от старого к молодому, каждый встаёт **сразу за своим `lead`**,
 * и уже уложенные звенья не двигаются. Результат читается одним проходом по
 * `next`.
 *
 * ### Почему «сразу за lead», а не поиск места сравнением
 *
 * В оригинале вставка ищет себе место, шагая вперёд по списку, пока встреченный
 * юнит свежее нового (`while lead.next && compare(...) < 0`). Здесь этого шага
 * нет, и не по недосмотру: очередь отсортирована от старого к молодому, поэтому
 * новый юнит **свежее всех уже уложенных**, и шаг вперёд не сделался бы ни разу.
 * Сравнение вырождается, а порядок детей одного `lead` получается сам собой:
 * каждый следующий (более свежий) втискивается перед предыдущими, и группа
 * оказывается разложена от свежего к старому — ровно как в `orderNaive`.
 *
 * Мало того, шаг вперёд не просто бесполезен, а вреден. Он сравнивает нового с
 * **соседом по плоскому списку**, не различая, чей это ребёнок. Пока каждый
 * ребёнок моложе своего `lead`, это одно и то же: поддерево целиком моложе
 * соседей, и шаг перепрыгивает его без разбора. Но `move` постит переехавший
 * узел заново, со свежей меткой, а его прежние `lead`-дети остаются со старой —
 * и с этого момента ребёнок бывает **старше** своего `lead`. Тогда шаг уводит
 * такого ребёнка за пределы поддерева, к чужим соседям. Позиционная вставка от
 * `lead` этим не страдает: место задаёт связь, а не метка.
 *
 * Расхождение не умозрительное: с восстановленным шагом краснеют и модульный
 * случай «ребёнок старше своего lead», и дифференциальный прогон на наборах из
 * настоящих операций (`__tests__/order-diff.prop.test.ts`).
 *
 * ### Почему в оригинале две карты, а здесь одна
 *
 * В baza раскладка идёт по **несвёрнутому** набору: в списке живут все версии
 * одного `self` от разных пиров сразу. Поэтому там `by_key` — сам список,
 * ключ звена это путь `head/peer/self` (у каждой версии свой), а `by_self` —
 * ответ на другой вопрос: «какая из версий этого `self` служит точкой привязки
 * детям», то есть победитель по LWW среди уже уложенных. Две карты — это два
 * разных ключа, а не кэш одного.
 *
 * Мы сворачиваем набор по `self` заранее (шаг 1), у каждого узла остаётся ровно
 * одна версия — и оба вопроса схлопываются в одну карту `self → звено`. Заодно
 * исчезают перекладывание уже уложенного звена и повторный обход очереди: в
 * оригинале они нужны как раз потому, что версии приезжают вперемешку.
 *
 * ### Что из оригинала не перенесено
 *
 * - **`Tine` и `slices`** — слияние форк-лендов. У нас форк-лендов пока нет,
 *   а вместе с ними не нужны ни разбавление компаратора номером слайса, ни
 *   дедупликация юнитов, пришедших из родительского ленда.
 * - **Выборка по `peer`** (`sand_ordered({ head, peer })`). Она меняет ключ
 *   звена с пути на `self` и служит чтению «что написал конкретный пир»; наш
 *   `order` читает ленд целиком.
 * - **Повторный проход по очереди** (`for cursor = queue.length - 1 ...` с
 *   рестартом после каждой укладки) — квадратичный поиск «кому уже можно».
 *   Заменён индексом `stalled`: ждущие подвешены к своему `lead` и разбираются
 *   каскадом в момент его укладки.
 *
 * @example
 * ```ts
 * order([b, a], ROOT).map(s => s.value) // → ['a', 'b'], если b.lead === a.self
 * ```
 */
export function order(sands: readonly Sand[], head: string): readonly Sand[] {
  // 1. Свёртка по `self`: у узла остаётся одна версия — победитель по LWW.
  //
  // Свой цикл, а не вызов `resolveNaive`: наивная реализация — референс, с
  // которым `order` сравнивают дифференциальным тестом, и общий код на входе
  // сделал бы часть этого сравнения самоподтверждающейся.
  const winners = new Map<string, Sand>()
  for (const sand of sands) {
    if (sand.head !== head) continue
    const prev = winners.get(sand.self)
    if (prev !== undefined && compare(sand, prev) >= 0) continue
    winners.set(sand.self, sand)
  }

  if (winners.size === 0) return []

  // 2. Очередь от старого к молодому — обратный {@link rank}.
  //
  // Направление выбрано не ради красоты: вставка почти всегда моложе своего
  // `lead` (иначе ей не на что было бы сослаться), поэтому в таком порядке
  // `lead` оказывается уложен раньше ребёнка и ждать почти никому не приходится.
  const queue = [...winners.values()]
  queue.sort((a, b) => rank(b, a))

  const guard: Slot = { self: ROOT, sand: null, next: null }
  const slots = new Map<string, Slot>([[ROOT, guard]])
  /** `lead` → дети, чьё звено ещё не появилось. Внутри — тот же порядок очереди. */
  const stalled = new Map<string, Sand[]>()
  /** Последнее звено списка: к нему приписываются сироты. */
  let tail = guard

  const place = (sand: Sand, lead: Slot): Slot => {
    const slot: Slot = { self: sand.self, sand, next: lead.next }
    lead.next = slot
    if (lead === tail) tail = slot
    slots.set(sand.self, slot)
    return slot
  }

  // Каскад итеративный, а не рекурсивный: отложиться может цепочка во всю длину
  // документа, а десять тысяч последовательных вставок — обычный текст, а не
  // патология, и рекурсия на нём ложится по стеку.
  const cascade = (from: Slot): void => {
    const stack: Slot[] = [from]

    while (stack.length > 0) {
      const lead = stack.pop() as Slot
      const kids = stalled.get(lead.self)
      if (kids === undefined) continue
      // Ждущие разбираются один раз: второй раз к этому `lead` уже никто не встанет.
      stalled.delete(lead.self)

      for (const kid of kids) {
        // Узел мог быть уложен раньше — как сирота, с которой начали кольцо.
        // Второе звено на тот же `self` задвоило бы элемент в чтении.
        if (slots.has(kid.self)) continue
        stack.push(place(kid, lead))
      }
    }
  }

  for (const sand of queue) {
    const lead = slots.get(sand.lead)

    if (lead === undefined) {
      // Ожидание не означает «недостижим»: после `move` переехавший узел
      // получает свежую метку и попадает в очередь **позже** собственных детей.
      // Такие разберутся каскадом; кто не разберётся — станет сиротой на шаге 3.
      const bucket = stalled.get(sand.lead)
      if (bucket === undefined) stalled.set(sand.lead, [sand])
      else bucket.push(sand)
      continue
    }

    cascade(place(sand, lead))
  }

  // 3. Сироты — всё, до чего не дотянулась ни одна связь: юниты с недоехавшим
  // `lead` и кольца из конкурентных `move`. Они дописываются в хвост по LWW,
  // каждая со своим поддеревом.
  //
  // Без этого шага живые по LWW элементы молча пропадали бы из чтения — а
  // сходимость этого не ловит: реплики теряют одни и те же элементы согласованно.
  // Оригинал поступает так же: очередь там разбирается до конца, и место
  // находится каждому юниту.
  if (stalled.size > 0) {
    const orphans: Sand[] = []
    for (const bucket of stalled.values()) {
      for (const sand of bucket) orphans.push(sand)
    }
    orphans.sort(rank)

    for (const orphan of orphans) {
      // Сироту мог утащить за собой предыдущий каскад: внутри кольца у каждого
      // узла есть свой `lead`, просто ни один из них не достижим снаружи.
      if (slots.has(orphan.self)) continue
      cascade(place(orphan, tail))
    }
  }

  // 4. Надгробия убираются из выдачи, но не из списка: на мёртвый узел ссылаются
  // по `lead` те, кто встал за ним, и без него они потеряли бы точку привязки.
  const out: Sand[] = []
  for (let slot = guard.next; slot !== null; slot = slot.next) {
    const sand = slot.sand
    if (sand !== null && sand.value !== null) out.push(sand)
  }

  return out
}
