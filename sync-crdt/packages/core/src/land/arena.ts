// v8:hot — арена лежит под каждым чтением ленда: `order`, `read` и арбитраж LWW
// достают байты через `bin(ref)`.
//
// ─── Зачем арена, а не буфер на юнит ─────────────────────────────────────────
//
// Отдельный `Uint8Array` на юнит — это ещё и объект вида, и `ArrayBuffer` на
// каждый юнит: 280.2 Б против 59.2 Б у арены (замер ADR-016, прототип
// «бинарный»). В арене же ссылка на юнит остаётся одним SMI и ложится в
// `Int32Array` без бокса.
//
// ─── Раскладка ссылки ────────────────────────────────────────────────────────
//
//   ref = (глава << 17) | смещение в главе
//
// Размер главы разобран у {@link CHUNK_BITS}: он выбран по потолку выносного
// значения, а число глав — по тому, чтобы `ref` остался SMI и лёг в
// `Int32Array` без бокса. Глава выделяется и больше НИКОГДА не переезжает: иначе выданный наружу вид смотрел
// бы в устаревший буфер, а кэш видов держал бы его живым — ровно та утечка, от
// которой байтовое представление должно избавлять.
//
// ─── Чужой буфер главой ──────────────────────────────────────────────────────
//
// Пачка приходит одним буфером, и `packDecode` уже разложил юниты внутри него.
// Копировать их к себе незачем — буфер регистрируется главами КАК ЕСТЬ (2.87 мс
// на 10 000 юнитов против 3.9–4.7 у копирующих путей, ADR-016). Буфер длиннее
// главы регистрируется НЕСКОЛЬКИМИ главами, и окна глав НАХЛЁСТЫВАЮТСЯ: глава
// `k` — это `bin.subarray(k * CHUNK)` до конца буфера, а не до конца главы.
// Нахлёст нужен ровно для одного случая: юнит, начавшийся под конец главы,
// продолжается за её границей, и без нахлёста его хвост оказался бы за пределом
// окна.
//
// ─── Переиспользование байт перекрытых версий (долг S4, закрыт на S5) ────────
//
// Раньше `alloc` только двигал указатель, и перезапись значения оставляла в
// арене мёртвый слот навсегда: память росла по ЧИСЛУ ПРАВОК, а не по объёму
// живых данных — ровно на сценарии «правят текст». Теперь перекрытый слот
// уходит в {@link Pool}, который склеивает соседей и колет блоки под меньший
// запрос.
//
// ГРАНИЦА КОНТРАКТА, названная вслух: `SandView` — окно в арену, и он
// действителен, пока его узел не перезаписан. После перезаписи ленд отдаёт новый
// вид (`Cell.ref` не совпадает — вид пересоздаётся), а прежний обязан быть
// отпущен. Реактивный слой это обеспечивает сам: смена победителя бьёт сигнал
// головы, и массив видов пересчитывается. Код, сложивший вид в переменную мимо
// реактивности и переживший запись, прочитает чужие байты — и это единственная
// причина, по которой `Land.write` возвращает СВЕЖИЙ вид, а не кэшированный.
//
// Чужие главы не освобождаются никогда: буфер `adopt` принадлежит вызывающему,
// и писать в него — портить чужие данные. Цена отказа от копии видна отдельным
// числом в {@link Arena.held}.

import { NO_ROOM, Pool } from '../binary/pool'

/** «Юнита у узла нет». Один сентинел на API (правило 3 горячего пути). */
export const NO_REF = -1

/**
 * Глава — 128 КиБ, а не 64, и это следствие выносных значений.
 *
 * Слот арены хранит юнит ВМЕСТЕ с его `ball` (та же раскладка, что в пачке), а
 * `ball` бывает до 65 535 байт: 48 + 65 536 = 65 584 в 64-килобайтную главу не
 * влезает. Раньше такой запрос молча уезжал за границу `Uint8Array` — запись за
 * пределом типизированного массива не бросает, она пропадает.
 *
 * Отдельная «большая глава» под такой слот была отвергнута: её адресный отрезок
 * налезал бы на соседние главы, и аллокатор склеивал бы блоки из разных буферов.
 * Расширение главы решает то же самое без особого случая.
 *
 * Потолок глав пересчитан так, чтобы `ref` остался SMI: 2¹⁴ × 2¹⁷ = 2³¹.
 */
export const CHUNK_BITS = 17
export const CHUNK = 1 << CHUNK_BITS
export const CHUNK_MASK = CHUNK - 1
/** Больше — и `ref` перестанет быть SMI, то есть перестанет лезть в `Int32Array`. */
export const CHUNKS_MAX = 1 << 14

/**
 * Хранилище байт юнитов: главы, которые не переезжают.
 *
 * @example
 * ```ts
 * const arena = new Arena()
 * const ref = arena.store(unit.bin, 0, unit.bin.length)
 * const bin = arena.bin(ref)
 * const at = ref & CHUNK_MASK
 * ```
 */
export class Arena {
  #chunks: Uint8Array[]
  /** Своя ли глава: чужую нельзя ни переиспользовать, ни зачистить. */
  #mine: boolean[]
  /** Куда пишем. Не последняя глава: после `adopt` в хвосте таблицы лежат чужие. */
  #head: number
  #fill: number
  /** Сколько байт выделено под собственные главы. */
  #owned: number
  /**
   * Байты ЧУЖИХ буферов, которые арена удерживает главами.
   *
   * Считается отдельно от {@link Arena.bytes}, а не вместе с ним: свои главы
   * измеряют цену хранения, чужие — цену отказа от копии, и складывать их значило
   * бы прятать вторую за первой. Пока этого счётчика не было, `bytes()` показывал
   * неизменные 65 536 у ленда, удерживающего 11 МБ чужих пачек, — то есть самый
   * крупный расход пути `adopt` был не виден вовсе.
   */
  #foreign: number
  /** Освобождённые слоты своих глав. Граница склейки — глава: за ней другой буфер. */
  readonly #pool: Pool

  constructor() {
    this.#chunks = [new Uint8Array(CHUNK)]
    this.#mine = [true]
    this.#head = 0
    this.#fill = 0
    this.#owned = CHUNK
    this.#foreign = 0
    this.#pool = new Pool(CHUNK)
  }

  /** Глава, в которой лежит юнит. Смещение внутри главы — `ref & CHUNK_MASK`. */
  bin(ref: number): Uint8Array {
    return this.#chunks[ref >>> CHUNK_BITS] as Uint8Array
  }

  /**
   * Место под `len` байт: сначала из освобождённых слотов, потом с конца главы.
   *
   * Переиспользованный слот ЗАЧИЩАЕТСЯ целиком. Иначе хвост до кратности 8
   * достался бы новому юниту от прежнего: длину пишущий выравнивает, а сами
   * байты хвоста не трогает, и они уехали бы в пачку и в подпись S6.
   */
  alloc(len: number): number {
    const spare = this.#pool.alloc(len)
    if (spare !== NO_ROOM) {
      const chunk = this.#chunks[spare >>> CHUNK_BITS] as Uint8Array
      const at = spare & CHUNK_MASK
      chunk.fill(0, at, at + len)
      return spare
    }

    // Сторож, а не ветка: формат ограничивает слот 48 + align8(65535) = 65 584
    // байтами, и глава выбрана вдвое больше именно поэтому. Молчать здесь нельзя —
    // запись за границу `Uint8Array` не бросает, она пропадает.
    if (len > CHUNK) {
      throw new RangeError(`slot of ${len} B does not fit into a ${CHUNK} B chunk`)
    }

    let at = this.#fill
    if (at + len > CHUNK) {
      this.#fresh()
      at = 0
    }
    this.#fill = at + len
    return (this.#head << CHUNK_BITS) | at
  }

  /**
   * Вернуть слот в оборот. Молча пропускает чужие главы — см. шапку файла.
   *
   * Байты НЕ зачищаются: зачистка перенесена в {@link Arena.alloc}, чтобы вид,
   * выданный до перезаписи, дочитал прежнее значение, а не наткнулся на нули.
   * Полезность спорная ровно до тех пор, пока слот не переиспользован, и это
   * записано в контракте вида.
   */
  free(ref: number, len: number): void {
    if (this.#mine[ref >>> CHUNK_BITS] !== true) return
    this.#pool.release(ref, len)
  }

  /**
   * Копия юнита в арену.
   *
   * `set` вместо ручного цикла там, где копируется буфер целиком: 13.6 нс против
   * 47.4 нс на 56 байтах. Со смещением пришлось бы звать `subarray` (ещё 35 нс и
   * вид в куче), поэтому там цикл честно дешевле.
   */
  store(src: Uint8Array, at: number, len: number): number {
    const ref = this.alloc(len)
    const dst = this.#chunks[ref >>> CHUNK_BITS] as Uint8Array
    const into = ref & CHUNK_MASK

    if (at === 0 && src.length === len) dst.set(src, into)
    else for (let i = 0; i < len; i++) dst[into + i] = src[at + i] as number

    return ref
  }

  /**
   * Принять чужой буфер главами, без копии. Возвращает номер первой главы;
   * ссылку на юнит по смещению в буфере даёт {@link refIn}.
   *
   * Плата за отказ от копии — буфер удерживается ЦЕЛИКОМ, включая юниты,
   * проигравшие LWW. Для дельты это выгодно, для пачки, где выжил один юнит из
   * тысячи, — нет; выбор между `adopt` и `apply` остаётся за вызывающим.
   */
  adopt(bin: Uint8Array): number {
    const span = Math.max(1, Math.ceil(bin.length / CHUNK))
    const base = this.#chunks.length
    if (base + span > CHUNKS_MAX) {
      throw new RangeError(`arena holds ${CHUNKS_MAX} chunks of ${CHUNK} B, and ${span} more is needed`)
    }

    for (let k = 0; k < span; k++) {
      this.#chunks.push(bin.subarray(k * CHUNK))
      this.#mine.push(false)
    }
    this.#foreign += bin.byteLength
    return base
  }

  /**
   * Вернуть главы, принятые с `base`, — для пачки, из которой не взято НИ ОДНОГО
   * юнита.
   *
   * Без этого повторная доставка уже известной пачки удерживает её буфер
   * навсегда: ссылок в него нет ни у одного узла, а `#chunks` его держит. Замер:
   * 200 доставок пачки в 56 КБ, `taken === 0` на каждой — `arrayBuffers`
   * 0.7 → 11.6 МБ, и `bytes()` при этом показывал прежние 65 536.
   *
   * Отсечь хвост безопасно ровно потому, что во время `adopt` собственных глав
   * не выделяется (`ready !== NO_REF` на каждом юните), — принятые главы лежат
   * сплошным хвостом таблицы. Сторожевое сравнение с `#head` держит это условие
   * проверяемым, а не подразумеваемым.
   */
  release(base: number, size: number): void {
    if (base <= this.#head) return
    this.#chunks.length = base
    this.#mine.length = base
    this.#foreign -= size
  }

  /** Сколько байт выделено под собственные главы. Чужие сюда не входят. */
  bytes(): number {
    return this.#owned
  }

  /** Сколько байт своих глав лежит в освобождённых слотах — знаменатель фрагментации. */
  spare(): number {
    return this.#pool.bytes()
  }

  /** Сколько байт чужих буферов удерживается главами. См. {@link Arena.release}. */
  held(): number {
    return this.#foreign
  }

  #fresh(): void {
    if (this.#chunks.length >= CHUNKS_MAX) {
      throw new RangeError(`arena holds ${CHUNKS_MAX} chunks of ${CHUNK} B`)
    }
    this.#head = this.#chunks.length
    this.#chunks.push(new Uint8Array(CHUNK))
    this.#mine.push(true)
    this.#owned += CHUNK
    this.#fill = 0
  }
}

/** Ссылка на юнит, лежащий со смещения `at` в буфере, принятом с главы `base`. */
export function refIn(base: number, at: number): number {
  return ((base + (at >>> CHUNK_BITS)) << CHUNK_BITS) | (at & CHUNK_MASK)
}
