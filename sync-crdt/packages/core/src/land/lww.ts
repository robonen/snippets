import type { Sand } from './sand'

/**
 * Порядок юнитов на таймлайне: `time ↓, peer ↑, tick ↓`
 * ([docs/04 §3](../../../../docs/04-crdt-core.md#3-lww)).
 *
 * Отрицательное — `a` идёт раньше `b`, то есть `a` «свежее» и побеждает по LWW.
 *
 * Три уровня арбитража нужны каждый по своей причине:
 * - `time ↓` — позднее изменение перекрывает раннее;
 * - `peer ↑` — детерминированный арбитр, когда два пира записали в одну секунду;
 * - `tick ↓` — внутри одной секунды у одного пира побеждает более поздняя запись.
 *
 * Компаратор — **строгий полный порядок** на юнитах одного пира: пара
 * `(time, tick)` у одного пира строго растёт при каждом посте
 * (см. `Replica.post`). Поэтому ноль возвращается только для юнитов, у которых
 * совпали все три поля, — а такие приходят из одного и того же поста.
 * Это важно: иначе `Array.sort` (стабильная) давала бы разный результат на
 * разных репликах в зависимости от порядка приёма.
 *
 * @example
 * ```ts
 * ;[older, newer].sort(compare) // → [newer, older]
 * ```
 */
export function compare(a: Sand, b: Sand): number {
  if (a.time !== b.time) return b.time - a.time
  if (a.peer !== b.peer) return a.peer < b.peer ? -1 : 1
  return b.tick - a.tick
}

/**
 * Перекрывает ли `next` уже лежащий `prev` по LWW.
 *
 * `prev === undefined` — места ещё не было занято, значит перекрывает.
 * Равенство трактуется как «не перекрывает»: повторная доставка того же
 * юнита не должна считаться изменением, иначе `converge` никогда не встанет.
 */
export function beats(next: Sand, prev: Sand | undefined): boolean {
  return prev === undefined || compare(next, prev) < 0
}
