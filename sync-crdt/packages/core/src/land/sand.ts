/**
 * Юнит данных на стадии C3 — обычный JS-объект, без бинарного слоя (S2 ещё не сделан).
 *
 * Sand — это **ребро** графа, а не узел ([docs/04 §2](../../../../docs/04-crdt-core.md)):
 * `head` держит вертикаль (кому принадлежу), `lead` — горизонталь (за кем стою),
 * `self` — то, на что ссылаются дети и следующие соседи.
 *
 * Порядок детей нигде не хранится: он **вычисляется** из цепочки `lead` при чтении.
 * Отсюда и берётся interleaving-free — см. {@link orderNaive}.
 *
 * @example
 * ```ts
 * const first: Sand = { self: 'a', head: ROOT, lead: ROOT, peer: 'p1', time: 1, tick: 0, value: 'hi' }
 * ```
 */
export interface Sand {
  /** Собственный id: дети ссылаются на него как на `head`, соседи — как на `lead`. */
  readonly self: string
  /** Родитель. {@link ROOT} — корень ленда. */
  readonly head: string
  /** Предыдущий сосед. {@link ROOT} — начало списка. */
  readonly lead: string
  /** Автор. Он же детерминированный арбитр при равном времени. */
  readonly peer: string
  /** Логические часы с физической подсказкой, секунды. */
  readonly time: number
  /** Счётчик внутри одной отметки времени. */
  readonly tick: number
  /** Полезная нагрузка. `null` — надгробие. */
  readonly value: unknown
}

/**
 * Единственный сентинел графа: и «нет родителя» (`head`), и «начало списка» (`lead`).
 *
 * Пустая строка, а не `null`, потому что она же используется как ключ карт —
 * иначе на каждом lookup'е пришлось бы держать два вида ключа.
 */
export const ROOT = ''

/** Надгробие ли: у мёртвого юнита значение выключено, но узел графа остаётся. */
export function dead(sand: Sand): boolean {
  return sand.value === null
}
