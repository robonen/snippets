// Контракт хранилища: одно обещание на память, IndexedDB, файл и OPFS.
//
// ─── Что здесь ОБЕЩАНО, а не просто объявлено ────────────────────────────────
//
// 1. **ПАЧКА, А НЕ ЮНИТЫ.** `load` отдаёт байты, `save` принимает байты, и это
//    не оптимизация, а исправление двух дефектов черновика docs/06 §1, где
//    интерфейс был объявлен на `readonly Unit[]`:
//    — список юнитов НЕ ВЫРАЖАЕТ выносных значений. Окно `SandUnit` кончается на
//      48-м байте, а `ball` лежит за ним; список юнитов молча приезжал бы без
//      значений, и хранилище для `ball` осталось бы недостижимым из собственного
//      интерфейса;
//    — материализация 100 000 видов стоит 192 Б на юнит сверх байтов (замер S2,
//      19 МБ объектов поверх 5.6 МБ данных), и всё это ленд немедленно
//      выбрасывает, забрав офсет. Байты уходят прямо в `Land.adopt` без копии.
//
// 2. **УДАЛЕНИЕ — ЭТО ЗАМЕЩЕНИЕ ПО КЛЮЧУ.** Черновик просил `save(land, {ins,
//    del})`. Пары `del` здесь нет, и это не упущение: в CRDT юнит не удаляют — на
//    него кладут надгробие, то есть НОВУЮ версию того же `(head, peer, self)`.
//    Перекрытая версия отличается от новой только полями, которых нет в ключе,
//    поэтому хранилище узнаёт о ней само: `unitKeyAt` совпал — слот тот же.
//    Отдельный `del` заставлял бы вызывающего сообщать то, что приёмник и так
//    выводит, и был бы третьим местом, где живёт правило LWW.
//
// 3. **АТОМАРНОСТЬ ПАЧКИ.** `save` применяется целиком или никак. Обрыв посреди
//    записи (падение вкладки, kill −9, выдернутый шнур) обязан оставить
//    хранилище на состоянии ДО этого `save` либо на состоянии ПОСЛЕ него, но
//    никогда — на половине. Как это достигается, решает реализация; для образа
//    на байтах это `Mirrors` (см. `mirrors.ts`).
//
// 4. **ПОРЯДОК.** Вызовы одного ленда исполняются в порядке подачи, и `load`
//    после `save` видит сохранённое. Между лендами порядка нет: ленд — единица
//    и хранения, и синхронизации, и блокировки.
//
// 5. **СИНХРОННОСТЬ НЕОБЯЗАТЕЛЬНА.** Каждый метод вправе вернуть значение или
//    промис. Память возвращает значение — благодаря этому мультипировые тесты
//    идут без единого `await` (docs/06 §2); IndexedDB и файл вернут промис, а
//    файбер подождёт (ADR-002). Вызывающий не выбирает — он зовёт через `sync()`
//    и не знает разницы.
//
// ─── Чего здесь НЕТ и почему ─────────────────────────────────────────────────
//
// Ленивой загрузки выносных значений. docs/06 §7 просит тест «ball > 32 МБ
// грузится лениво и не попадает в память при `load()`», но такого `ball` не
// бывает: `sizeBig` — два байта, потолок 65 535. И главное — «санд без
// приложенного балла» НЕ ВЫРАЗИМ в формате: маркера «балл отделён» в раскладке
// нет, парсер обязан прочесть `align8(size)` байт сразу за сандом (docs/03 §2,
// «Открытый вопрос», развилка отложена на S7). Поэтому `load` везёт значения
// вместе с юнитами, а {@link UnitStore.ball} остаётся ручкой для того, кто
// спрашивает значение ПО ХЭШУ, не поднимая ленд, — и точкой, к которой S7
// прицепит досылку недостающих баллов.

import type { LandId } from '../binary/pack'

/**
 * Отказ хранилища: образ не разбирается, оба зеркала грязные, ленд не тот.
 * Исключительное, а не значение (PRINCIPLES.md, раздел «Ошибки»).
 *
 * `at` — место: `ленд AQIDBAUGBwg, зеркало 0`.
 */
export class StoreError extends Error {
  readonly reason: string
  readonly at: string

  constructor(reason: string, at: string, cause?: unknown) {
    super(at === '' ? reason : `${reason} — ${at}`, cause === undefined ? undefined : { cause })
    this.name = 'StoreError'
    this.reason = reason
    this.at = at
  }
}

/** То, что метод хранилища вправе вернуть: значение или промис. См. п. 5 в шапке. */
export type Awaitable<T> = T | Promise<T>

/**
 * Хранилище юнитов. Одинаково исполняется памятью, IndexedDB, файлом и OPFS.
 *
 * @example
 * ```ts
 * const store = memoryStore()
 * const vault = openVault({ store, id, land })     // гидрация + автосохранение
 * const space = createSpace({ land, id, ready: vault.ready })
 * ```
 */
export interface UnitStore {
  /**
   * Всё, что есть по ленду, — **валидной пачкой** (ADR-005).
   *
   * Незнакомый ленд даёт пустую пачку (один заголовок), а не отказ: «ленда ещё
   * нет» — это штатное состояние первого запуска, а не исключительное.
   *
   * Байты принадлежат ВЫЗЫВАЮЩЕМУ: хранилище отдаёт копию, потому что `adopt`
   * держит буфер главами арены, а хранилище продолжает править свой образ на
   * месте. Общее окно означало бы, что ленд видит чужие правки задним числом.
   */
  load(land: LandId): Awaitable<Uint8Array>

  /**
   * Влить пачку изменений. Атомарно: целиком или никак (п. 3 в шапке).
   *
   * Юнит с тем же ключом замещает прежнюю версию В ТОМ ЖЕ слоте, если длина
   * совпала, — на этом держится бюджет «после 10 000 save/delete файл ≤ 1.3× от
   * полезного объёма».
   */
  save(land: LandId, pack: Uint8Array): Awaitable<void>

  /**
   * Выносное значение по его 12-байтовому `shot`, не поднимая ленд.
   *
   * `undefined` — значения нет: ожидаемый исход возвращается значением, а не
   * броском. Пока эту ручку зовёт только тот, кому нужно одно значение из
   * большого ленда; S7 прицепит к ней досылку недостающих баллов, когда в
   * формате появится маркер «балл отделён».
   */
  ball(land: LandId, shot: Uint8Array): Awaitable<Uint8Array | undefined>

  /** Забыть ленд целиком. Незнакомый ленд — не ошибка. */
  drop(land: LandId): Awaitable<void>

  /** Какие ленды известны — для восстановления после перезагрузки. */
  lands(): Awaitable<readonly LandId[]>
}

/**
 * Носитель образа: кусок памяти, файл, `FileSystemSyncAccessHandle`, запись IDB.
 *
 * Разделение с {@link UnitStore} проходит по оси изменения: здесь живёт «как
 * байты доезжают до носителя», там — «что такое ленд». Благодаря этому
 * `PackImage` и `Mirrors` — весь механизм арены и атомарности — пишутся ОДИН
 * раз, а fs/opfs добавляют к ним по три метода.
 *
 * ПОЧЕМУ образ отдаётся окном, а не читается кусками: юниты лежат по офсетам, и
 * разбор идёт по всему файлу. Ленд из 100 000 юнитов — это 10 МБ, которые всё
 * равно окажутся в памяти; чтение вразнобой добавило бы обращений к носителю, не
 * сэкономив ни байта.
 */
export interface Volume {
  /** Образ целиком. Писать можно прямо сюда, но каждый участок — через {@link Volume.wrote}. */
  bin(): Uint8Array
  /** Расширить образ до `size` байт (новые байты нулевые) и вернуть новое окно. */
  grow(size: number): Uint8Array
  /**
   * Участок `[at, at + size)` изменён.
   *
   * Носитель обязан довезти его до устройства не позже {@link Volume.flush}.
   * Именно здесь обрывается запись в тесте `kill9`: том бросает, отдав ровно
   * столько байт, сколько ему разрешили.
   */
  wrote(at: number, size: number): void
  /** Довести записанное до устойчивого носителя (`fsync`, `flush`, `commit`). */
  flush(): void
}
