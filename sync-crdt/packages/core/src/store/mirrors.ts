// Атомарность без журнала: два образа, из которых читают ПЕРВЫЙ ДОПИСАННЫЙ.
//
// ─── Задача ──────────────────────────────────────────────────────────────────
//
// `save` обязан примениться целиком или никак, а обрыв — падение вкладки,
// kill −9, выдернутый шнур — не имеет права оставить данные на половине. Это
// гейт корректности стадии: `store.kill9` бьёт запись на 1000 позициях.
//
// ─── Что предлагал черновик docs/06 §4 и почему это не работает ──────────────
//
// Черновик описывал yin-yan так: клонировать свежий файл в запасной, применить
// правку к запасному, сбросить на диск, поменять роли, применить к бывшему
// свежему. Читать — «более свежий по mtime».
//
// Два независимых дефекта.
//
// 1. **mtime отвечает не на тот вопрос.** Обрыв ПОСРЕДИ записи оставляет файл
//    одновременно самым новым и негодным, и правило «читать новейший» выбирает
//    именно его. Нужен признак «ДОПИСАН», а его у mtime нет.
// 2. **Клонирование файла на каждое сохранение.** Сохранение батча из 1000
//    юнитов копировало бы весь ленд — 10 МБ на 100 000 юнитов при бюджете
//    30 мс. Клон нужен ровно в одном случае: когда зеркала РАЗОШЛИСЬ, то есть
//    после обрыва.
//
// ─── Что здесь ───────────────────────────────────────────────────────────────
//
// Признак «дописан» — метка секции `"LAND"` (см. {@link PackImage.soil}), а роли
// зеркал ПОСТОЯННЫ: сначала всегда пишется сторона 0, потом сторона 1.
// Постоянство ролей и снимает вопрос «кто новее» вовсе:
//
//   покой            обе дописаны и одинаковы          → читаем 0
//   пишем 0          0 грязная, 1 дописана (старое)    → читаем 1, батч потерян целиком
//   0 записана       0 дописана (новое), 1 ещё старая  → читаем 0, батч сохранён
//   пишем 1          0 дописана (новое), 1 грязная     → читаем 0
//
// Ни в одной строке нет состояния «половина батча»: грязная сторона отвергается
// по метке, а дописанная либо вся старая, либо вся новая. Обеих грязных не
// бывает — сторону 0 пачкают только когда сторона 1 дописана, и наоборот.
//
// Плата — двойная запись ИЗМЕНЁННЫХ байт (а не двойное копирование файла) и
// двойной объём на носителе. Для локальной базы это дешевле журнала с компакцией.
//
// ─── Почему сторон массив, а не пара ─────────────────────────────────────────
//
// Одна сторона — законная конфигурация: она отказывается от устойчивости к
// обрыву в обмен на половину записи и половину объёма. Ею меряется ЦЕНА зеркал в
// бенче (иначе цифра «сколько стоит атомарность» неоткуда не берётся) и ею же
// живут тесты, которым обрыв безразличен. Протокол при этом ОДИН: цикл по
// сторонам в постоянном порядке.

import type { LandId } from '../binary/pack'
import { PackImage } from './image'
import { StoreError, type Volume } from './store'

/**
 * Набор зеркал одного ленда.
 *
 * @example
 * ```ts
 * const mirrors = Mirrors.open([yin, yan], id)
 * mirrors.save(pack)          // атомарно
 * mirrors.pack()              // то, что прочтётся после перезапуска
 * ```
 */
export class Mirrors {
  readonly #sides: PackImage[]

  private constructor(sides: PackImage[]) {
    this.#sides = sides
  }

  /**
   * Открыть зеркала, починив те, что оборвались.
   *
   * @throws {StoreError} если ни одна сторона не дописана, а носитель при этом
   * не пуст: это потеря данных, и молчать о ней нельзя — пустой ленд на месте
   * непрочитанного выглядел бы как «всё в порядке, просто ничего нет».
   */
  static open(volumes: readonly Volume[], id: LandId): Mirrors {
    if (volumes.length === 0) throw new StoreError('zero mirrors', `land ${id.str}`)

    // Ведущей становится первая сторона, которая не только ПОМЕЧЕНА целой, но и
    // РАЗБИРАЕТСЯ. Разница не теоретическая: метка занимает четыре байта и может
    // долететь тогда, когда тело не долетело, а носитель — испортиться и мимо
    // наших записей. Первая редакция брала первую помеченную и сразу её
    // разбирала: одна негодная сторона роняла открытие целиком — при исправной
    // второй. Зеркало заводят ровно затем, чтобы этого не случалось.
    let source = -1
    let master: PackImage | null = null
    let refused: unknown = null
    for (let i = 0; i < volumes.length; i++) {
      if (!PackImage.clean(volumes[i] as Volume)) continue
      try {
        master = PackImage.open(volumes[i] as Volume, id)
        source = i
        break
      } catch (error) {
        // Помечена целой, а не читается: сторона негодна как источник, но может
        // быть починена копией с той, которая читается.
        refused = error
      }
    }

    if (source < 0 && refused !== null) {
      throw new StoreError(
        `no marked side could be parsed: ${String(refused)}`,
        `land ${id.str}`,
      )
    }

    if (source < 0) {
      const fresh = volumes.every(volume => volume.bin().length === 0)
      if (!fresh) {
        throw new StoreError(
          'no mirror was fully written — the interruption happened before any side became whole',
          `land ${id.str}`,
        )
      }
      return new Mirrors(volumes.map(volume => PackImage.create(volume, id)))
    }

    // К этой строке `master` заведомо не null: `source >= 0` ставится только
    // вместе с ним. Сужаем проверкой, а не приведением — приведение здесь
    // молчало бы, если инвариант когда-нибудь сломают правкой выше.
    if (master === null) throw new StoreError('the master side is not open', `land ${id.str}`)
    const raw = master.raw()
    const sides: PackImage[] = []

    for (let i = 0; i < volumes.length; i++) {
      if (i === source) {
        sides.push(master)
        continue
      }

      const volume = volumes[i] as Volume
      // ЗДОРОВОЕ ЗЕРКАЛО НЕ ТРОГАЕТСЯ. Первая редакция чинила копией ВСЕ стороны,
      // кроме ведущей, — то есть переписывала целый образ на каждом открытии,
      // включая штатное. Поймал это `kill9`: том, у которого запись оборвана на
      // N-м байте, тратил весь свой запас на восстановление, которого не
      // требовалось, и обрыв случался не там, где тест его ставил.
      if (PackImage.clean(volume) && sameBytes(volume.bin(), raw)) {
        sides.push(PackImage.open(volume, id))
        continue
      }

      // Разошедшееся зеркало восстанавливается КОПИЕЙ, и это единственное место,
      // где копируется весь образ. Обычное сохранение копирует только изменённые
      // слоты — ровно поэтому клон убран из горячего пути.
      const spare = PackImage.create(volume, id)
      spare.clone(raw)
      sides.push(spare)
    }

    // Роли постоянны: читать обязаны сторону 0. Если целой оказалась не она,
    // порядок восстановлен копией выше, и обе стороны теперь одинаковы.
    return new Mirrors(sides)
  }

  /** Сколько зеркал держится. */
  count(): number {
    return this.#sides.length
  }

  /** Пачка живых юнитов — то, что прочтётся и после перезапуска. */
  pack(): Uint8Array {
    return (this.#sides[0] as PackImage).pack()
  }

  /** Выносное значение по хэшу. */
  ball(shot: Uint8Array): Uint8Array | undefined {
    return (this.#sides[0] as PackImage).ball(shot)
  }

  /** Байт на носителе — суммой по сторонам: зеркала стоят места, и это видно. */
  bytes(): number {
    let out = 0
    for (const side of this.#sides) out += side.bytes()
    return out
  }

  /** Полезный объём одной стороны — знаменатель бюджета «файл ≤ 1.3×». */
  live(): number {
    return (this.#sides[0] as PackImage).live()
  }

  /** Сколько юнитов лежит в образе. */
  units(): number {
    return (this.#sides[0] as PackImage).count()
  }

  /**
   * Влить пачку атомарно: сторона за стороной, в постоянном порядке.
   *
   * Порядок операций внутри стороны — и есть весь протокол: пометить грязной,
   * дописать, пометить целой. Между сторонами нет ни одного момента, когда
   * грязными были бы обе, — разбор состояний в шапке файла.
   */
  save(pack: Uint8Array): void {
    for (const side of this.#sides) {
      side.soil()
      side.merge(pack)
      side.seal()
    }
  }

  /** Забыть содержимое: ленд удалён целиком. Тем же протоколом, что и запись. */
  wipe(): void {
    for (const side of this.#sides) {
      side.soil()
      side.reset()
      side.seal()
    }
  }
}

/**
 * Совпадают ли образы побайтово.
 *
 * ПОЧЕМУ СРАВНЕНИЕ, А НЕ ПРИЗНАК. Есть ровно одно состояние, в котором обе
 * стороны дописаны, но РАЗНЫЕ: обрыв между тем, как сторона 0 стала целой, и
 * тем, как сторону 1 пометили грязной. Отличить его по метке нельзя — метка
 * говорит «дописан», а не «свеж», — и вводить рядом с ней счётчик поколений
 * значило бы завести в формате поле, которого там нет. Сравнение точное, стоит
 * один проход по образу и делается ОДИН раз на открытие, а не на сохранение.
 */
function sameBytes(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false
  }
  return true
}
