// Гидрация и автосохранение: ленд, поднятый из хранилища, и его связь с ним.
//
// ─── Чтение остаётся синхронным (ADR-002) ────────────────────────────────────
//
// Ленд едет из IndexedDB, то есть асинхронно. Прикладной код при этом пишет
// `post.title()` и получает строку — не промис, не `await`, не «загрузка…».
// Работает это не магией, а приостановкой файбера: `sync()` бросает промис,
// текущее вычисление откладывается целиком и ПЕРЕЗАПУСКАЕТСЯ, когда данные
// приехали. Наружу приостановка не протекает вовсе — вызывающий видит либо
// значение, либо ту же приостановку выше по стеку.
//
// Отсюда форма {@link Vault.ready}: это не `await`, не колбэк и не флаг, а
// обычное чтение канала, которое ИНОГДА приостанавливает. Подключается оно
// одной строкой — `createSpace({ ready: vault.ready })`, — и дальше приостановка
// живёт под КАЖДЫМ чтением поля, потому что все чтения слоя проходят через
// состав детей головы.
//
// ─── Где приостановка НЕ ставится и почему ───────────────────────────────────
//
// На отдельном выносном значении. Соблазн есть: «грузить `ball` лениво, а до
// того приостанавливать читателя этого поля». Не выйдет, и причина не в лени —
// «санд без приложенного балла» НЕ ВЫРАЗИМ в формате (docs/03 §2, «Открытый
// вопрос»). Пока маркера нет, ленд не может представить такой юнит, а хранилище
// не может его отдать. Развилка ждёт S7 вместе с досылкой недостающих баллов.
//
// ─── Сохранение батчами, а не по юниту (docs/06 §6) ──────────────────────────
//
// Ленд ведёт журнал несохранённого и реактивно сообщает его размер. Хранилище
// подписано на это число и просыпается МИКРОЗАДАЧЕЙ: транзакция из ста правок
// уезжает одним `save`, а не сотней. Порядок обязателен и обратный тому, что
// кажется: сначала журнал забирается целиком (`land.flush`), потом пачка уходит
// в хранилище, — иначе правка, сделанная во время сохранения, потерялась бы
// между двумя вызовами.

import { async, computed, pin, sync, untracked, watchEffect } from '@sync/fiber'
import type { LandId } from '../binary/pack'
import type { Land } from '../land/land'
import { StoreError, type UnitStore } from './store'

export interface VaultOptions {
  readonly store: UnitStore
  readonly id: LandId
  readonly land: Land
  /**
   * Куда сообщать об отказах хранилища. По умолчанию — `console.error`.
   *
   * Отдельная ручка, а не бросок: сохранение идёт в микрозадаче, и бросить там
   * значит получить необработанное отклонение промиса вместо диагностики.
   */
  readonly report?: (error: unknown) => void
}

export interface Vault {
  readonly id: LandId
  readonly land: Land
  /**
   * Разрешение читать. Приостанавливает файбер, пока ленд едет из хранилища, и
   * ничего не стоит после. Передаётся в `createSpace({ ready })`.
   */
  ready(): void
  /** Промис на «ленд поднят» — для кода, который живёт вне файберов. */
  opened(): Promise<void>
  /** Сохранить несохранённое немедленно, не дожидаясь микрозадачи. */
  save(): void
  /** Отписаться и перестать сохранять. Ленд остаётся жив. */
  close(): void
}

/** Стабильная ссылка для `sync()`: стрелка на месте вызова совпадения не даст. */
function loadFrom(store: UnitStore, id: LandId): Uint8Array | Promise<Uint8Array> {
  return store.load(id)
}

/**
 * Связать ленд с хранилищем: поднять из него и сохранять в него.
 *
 * Явный DI (ADR-010): хранилище передаётся, а не берётся из ambient. Благодаря
 * этому в одном процессе живут несколько узлов с разными хранилищами, и
 * мультипировый тест — это просто два `openVault`.
 *
 * @example
 * ```ts
 * const vault = openVault({ store, id, land })
 * const space = createSpace({ land, id, ready: vault.ready })
 * post.title()          // приостановится, пока ленд едет, и вернёт значение
 * ```
 */
export function openVault(options: VaultOptions): Vault {
  const { store, id, land } = options
  const report = options.report ?? defaultReport

  /**
   * Гидрация. `pin()` обязателен: канал держит ленд и не имеет права быть
   * собранным, когда читателей временно нет — иначе следующее чтение загрузило
   * бы ленд заново и потеряло локальные правки, сделанные между чтениями.
   */
  const loaded = computed(function hydrated(): number {
    pin()
    const bin = sync(loadFrom, store, id)
    land.adopt(bin)
    // Журнал включается ПОСЛЕ приёма: иначе только что загруженные юниты
    // немедленно уехали бы обратно в хранилище — 100 000 лишних записей на
    // каждый старт при бюджете загрузки 500 мс.
    land.track()
    return bin.length
  })

  let closed = false
  let queued = false

  /**
   * Пачки, которые хранилище не приняло. Отдаются при следующей попытке первыми.
   *
   * ПОЧЕМУ ЭТО ЕСТЬ. `land.flush(id)` ОЧИЩАЕТ журнал несохранённого, и делает это
   * ДО того, как выяснится, приняло ли хранилище пачку. Первая редакция на отказе
   * звала `report`, то есть по умолчанию `console.error`, — и на этом правки
   * пользователя исчезали НАВСЕГДА и МОЛЧА: из журнала они уже вычеркнуты, в
   * хранилище не попали, повторить некому.
   *
   * Для local-first это худший из возможных дефектов: весь смысл в том, что
   * данные принадлежат пользователю и переживают что угодно. Диск, полный на
   * запись, квота IndexedDB, отозванное разрешение — не экзотика, а будни.
   *
   * Поэтому непринятое НЕ выбрасывается, а копится и уезжает следующей попыткой.
   * Порядок сохраняется: пачки применяются в том же порядке, в каком родились, —
   * иначе более старая версия юнита легла бы поверх новой.
   */
  const pending: Uint8Array[] = []

  function drain(): void {
    queued = false
    if (closed) return

    // `untracked` обязателен: сохранение читает журнал ленда, и подписка на него
    // означала бы, что сохранение будит само себя своей же очисткой.
    // Пустую пачку не копим: `flush` на нетронутом ленде отдаёт один заголовок.
    if (untracked(() => land.unsaved()) > 0) pending.push(untracked(() => land.flush(id)))
    if (pending.length === 0) return

    // Одной пачкой. Склейка ЗАКОДИРОВАННЫХ пачек побайтово сама является
    // валидной пачкой: по формату (docs/03 §3) за секцией ленда просто идёт
    // следующий заголовок. Поэтому обещание хранилища «целиком или никак»
    // распространяется на всё накопленное, а порядок правок сохраняется.
    const pack = pending.length === 1 ? (pending[0] as Uint8Array) : concat(pending)
    const held = pending.length

    const kept = (error: unknown): void => {
      // Пачки остаются в очереди — они уже там, снимаем их только при успехе.
      report(new StoreError(
        `store did not accept the pack, it is kept for a retry (${held} queued): ${String(error)}`,
        `land ${id.str}`,
      ))
    }

    try {
      const done = store.save(id, pack)
      if (done instanceof Promise) {
        done.then(() => { pending.splice(0, held) }, kept)
      } else {
        pending.splice(0, held)
      }
    } catch (error) {
      kept(error)
    }
  }

  const stop = watchEffect(function saving() {
    // Читаем через тот же канал, что и все остальные: пока ленд не поднят,
    // сохранять нечего, а приостановка здесь заодно ЗАПУСКАЕТ гидрацию — иначе
    // ленд поднимался бы только по первому чтению поля.
    loaded()

    if (land.unsaved() === 0) return
    if (queued || closed) return
    queued = true
    queueMicrotask(drain)
  })

  return {
    id,
    land,
    ready(): void {
      loaded()
    },
    opened(): Promise<void> {
      // `async()` — штатный выход из мира файберов в мир промисов: он поднимает
      // наблюдателя, ловит приостановку и разрешает промис, когда вычисление
      // действительно досчиталось. Своя обвязка вокруг `watchEffect` здесь была
      // бы третьей копией той же логики.
      return async(() => {
        loaded()
      })
    },
    save(): void {
      if (closed) throw new StoreError('store is disconnected from the land', `land ${id.str}`)
      drain()
    },
    close(): void {
      closed = true
      stop()
    },
  }
}

/** Склейка закодированных пачек: результат — снова валидная пачка. */
function concat(parts: readonly Uint8Array[]): Uint8Array {
  let size = 0
  for (const part of parts) size += part.length
  const out = new Uint8Array(size)
  let at = 0
  for (const part of parts) {
    out.set(part, at)
    at += part.length
  }
  return out
}

function defaultReport(error: unknown): void {
  console.error('[@sync/core] store did not accept the pack:', error)
}
