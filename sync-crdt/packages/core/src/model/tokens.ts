// ─── Токенизация: «разделитель + слово» ──────────────────────────────────────
//
// Чистые функции: ни ленда, ни файберов, ни состояния. Отдельным файлом по той
// же оси, по которой они отделены в корпусе (`text/tokens/`), и потому же
// проверяются отдельным набором — десятью примерами baza дословно.
//
// ПОЧЕМУ ТОКЕН, А НЕ СИМВОЛ. Посимвольное хранение даёт идеальное слияние и
// платит юнитом за букву: абзац на 78 знаков — 78 юнитов по ~56 Б заголовка
// (docs/03 §2), то есть 4.4 КБ на строку текста.
//
// ЧИСЛО ИЗМЕРЕНО, а не оценено: 100 037 знаков обычного русского текста дают
// 17 496 токенов и 18 955 юнитов вместе с абзацами (`bench/text.mjs`), то есть
// в 5.3 раза меньше, чем посимвольно, — примерно 6 знаков на юнит. Заявленный
// изначально «порядок» замером НЕ подтвердился, и число здесь стоит
// измеренное: слово в русском тексте короче, чем кажется, а ведущий пробел
// добавляет к нему всего один знак. Слияние при этом сохраняется полностью —
// конфликтуют только пиры, правившие ОДНО слово.
//
// ─── Три инварианта, каждый ломается незаметно ───────────────────────────────
//
// 1. ВЕДУЩИЙ ПРОБЕЛ ПРИНАДЛЕЖИТ СЛЕДУЮЩЕМУ ТОКЕНУ: `'foo bar'` → `['foo',
//    ' bar']`, а не `['foo', ' ', 'bar']`. Пробел отдельным юнитом был бы лишней
//    точкой конфликта — два пира, вставляющие соседние слова, правили бы общий
//    разделитель.
//
// 2. ТОКЕНИЗАЦИЯ ТОТАЛЬНА: `tokenize(s).join('') === s` для ЛЮБОЙ строки.
//    У baza это не так, и молча: `String.match` с флагом `g` просто
//    ПЕРЕШАГИВАЕТ позицию, на которой ни одно правило не сошлось, — символ
//    исчезает, а ошибки нет. Замерено на её наборе правил, четыре живых
//    контрпримера:
//
//     'foo\n  bar'  → ['foo','\n',' bar']   — потерян второй пробел
//     '\u2003a'      → ['a']                 — потеряна вырезка U+2003
//     '\u00a0\u2003x' → [' ','x']             — потеряна она же
//     'a\u2028b'     → ['a','b']             — потерян разделитель строк U+2028
//
//    Первая тройка — работа `forbid_after(line_end)` и узкого класса ведущего
//    пробела `[ \u00a0]`, четвёртая — того, что U+2028 не подходит ни под одно
//    правило вовсе. Для СЛИВАЕМОГО текста это не косметика: `str()` определён
//    как склейка токенов, значит запись теряла бы символы у автора и
//    расходилась бы с тем, что он набрал. Лечится хвостовым правилом «любой
//    одиночный символ» — оно стоит одной альтернативы и делает тотальность
//    свойством конструкции, а не удачи. Лишние `forbid_after` при этом сняты:
//    с хвостовым правилом они уже ничего не защищают, а токенов дают больше
//    (`'\n   x'` — три токена против двух).
//
// 3. ГРАНИЦА КАРЕТКИ ВКЛЮЧИТЕЛЬНА — но это уже свойство `text.ts`, здесь только
//    длины токенов, из которых она считается.

/** Абзац несёт СВОЙ перевод строки: `'a\nb'` → `['a\n', 'b']`. */
const PARAGRAPHS = /[^\n]*\n|[^\n]+$/g

/**
 * Правила токена, В ПОРЯДКЕ ПРИОРИТЕТА. Порядок — часть контракта: `word` до
 * `spaces` и есть инвариант 1, а `line-break` до всего пробельного — то, из-за
 * чего разделитель абзацев не уезжает в общий пробельный токен.
 */
const RULES: readonly string[] = [
  // Перевод строки. `\r\n` первым: иначе он распался бы на два токена.
  '\\r\\n|\\r|\\n',
  // Отступ табами — своим токеном, чтобы правка отступа не трогала первое слово.
  '\\t+',
  // Эмодзи: база, модификатор тона и сколько угодно склеек через ZWJ. Семья из
  // четырёх кодовых точек обязана быть ОДНИМ токеном, иначе слияние разрежет её
  // пополам и получится не человек.
  '\\p{Extended_Pictographic}\\p{Emoji_Modifier}?(?:\\p{Emoji_Component}\\p{Extended_Pictographic}\\p{Emoji_Modifier}?)*',
  // Ссылка целиком: точка внутри URL не граница слова.
  '\\bhttps?:\\/\\/[^\\s,.;:!?")]+(?:[,.;:!?")][^\\s,.;:!?")]+)+',
  // Слово с заглавной. Отдельно от строчного ради CamelCase: `Foo1BAR2` — две
  // правки, а не одна.
  '[ \\u00a0]?[\\p{Lu}\\p{Diacritic}\\p{N}]+[\\p{Ll}\\p{Diacritic}\\p{N}]*',
  // Слово строчными.
  '[ \\u00a0]?[\\p{Ll}\\p{Diacritic}\\p{N}]+',
  // Серия пробелов, кроме последнего: последний уедет ведущим у слова.
  '\\s+(?=\\s)',
  // Одиночный пробел, за которым не слово: перед словом он его ведущий.
  '\\s(?![\\s\\p{Lu}\\p{Ll}\\p{Diacritic}\\p{N}])',
  // Пунктуация и символы.
  '[ \\u00a0]?[^\\p{Lu}\\p{Ll}\\p{Diacritic}\\p{N}\\s]+',
  // Хвостовое правило — инвариант 2. Ниже него провалиться некуда.
  '[\\s\\S]',
]

const TOKENS = new RegExp(RULES.join('|'), 'gu')

/** Пустая выдача — одна на модуль (правило 7 горячего пути). */
const NO_WORDS: readonly string[] = Object.freeze([])

/**
 * Сколько байт займёт значение токена внутри юнита.
 *
 * 62 — потолок inline-значения (docs/03 §2: 63 занято маркером выноса в `ball`),
 * заголовок строки в `vary` — до двух байт, отсюда 60. Токен длиннее ленд бы
 * ОТВЕРГ броском, то есть вставка длинного слова роняла бы запись целиком.
 */
const WORD_MAX = 60

/**
 * Порог дешёвой отсечки: символ UTF-16 весит не больше 4 байт в UTF-8, значит
 * слово короче этого заведомо влезает и мерить его незачем.
 */
const SHORT = 15

/**
 * Токены строки. `tokenize(s).join('') === s` — ВСЕГДА (инвариант 2).
 *
 * @example
 * ```ts
 * tokenize('foo bar')   // ['foo', ' bar']
 * tokenize('Foo1BAR2')  // ['Foo1', 'BAR2']
 * tokenize('foo  bar')  // ['foo', ' ', ' bar']
 * ```
 */
export function tokenize(text: string): readonly string[] {
  if (text === '') return NO_WORDS
  // `match` с флагом `g` сам обнуляет `lastIndex`, поэтому регулярка модульная
  // и разделяемая. С `test` так было бы нельзя — там `lastIndex` живёт между
  // вызовами (см. ту же ловушку в `t.pattern`).
  return text.match(TOKENS) ?? NO_WORDS
}

/**
 * Абзацы. Перевод строки остаётся у СВОЕГО абзаца, поэтому склейка возвращает
 * исходный текст, а правка одного абзаца не задевает юниты остальных.
 *
 * @example
 * ```ts
 * splitParagraphs('a\nb')   // ['a\n', 'b']
 * splitParagraphs('')       // []
 * splitParagraphs('a\n\nb') // ['a\n', '\n', 'b']
 * ```
 */
export function splitParagraphs(text: string): readonly string[] {
  if (text === '') return NO_WORDS
  return text.match(PARAGRAPHS) ?? NO_WORDS
}

/** Одним ли абзацем читается строка: ни одного `\n`, кроме, может быть, последнего. */
export function single(text: string): boolean {
  if (text === '') return false
  const at = text.indexOf('\n')
  return at < 0 || at === text.length - 1
}

/** Длина в байтах UTF-8 без аллокации: `TextEncoder` строил бы массив на каждое слово. */
export function utf8Len(text: string): number {
  let size = 0
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i)
    if (code < 0x80) size += 1
    else if (code < 0x800) size += 2
    else if (code >= 0xd800 && code < 0xdc00 && i + 1 < text.length) {
      // Суррогатная пара — одна кодовая точка в четырёх байтах.
      size += 4
      i += 1
    } else size += 3
  }
  return size
}

/**
 * Разрезать слова, не влезающие в юнит.
 *
 * Без этого одна вставленная ссылка на сотню байт роняла бы `body(next)`
 * броском из ленда — а бросок на записи текста означает потерянный ввод
 * пользователя. Склейка сохраняется, поэтому чтение возвращает ровно то, что
 * записали; резать по кодовым точкам обязательно — разрезанная суррогатная пара
 * даёт одинокий суррогат, и на нём бросает уже кодек `vary`.
 *
 * Быстрый путь возвращает ТОТ ЖЕ массив: длинные слова редки, и платить
 * аллокацией за каждую строку текста незачем.
 */
export function fitTokens(words: readonly string[]): readonly string[] {
  let long = false
  for (let i = 0; i < words.length; i++) {
    if (!fits(words[i] as string)) {
      long = true
      break
    }
  }
  if (!long) return words

  const out: string[] = []
  for (let i = 0; i < words.length; i++) {
    const word = words[i] as string
    if (fits(word)) {
      out.push(word)
      continue
    }
    cut(out, word)
  }
  return out
}

function fits(word: string): boolean {
  return word.length <= SHORT || utf8Len(word) <= WORD_MAX
}

/** Нарезка длинного слова по кодовым точкам, кусками не больше {@link WORD_MAX} байт. */
function cut(out: string[], word: string): void {
  let from = 0
  let size = 0
  for (let i = 0; i < word.length; i++) {
    const code = word.charCodeAt(i)
    const pair = code >= 0xd800 && code < 0xdc00 && i + 1 < word.length
    const cost = code < 0x80 ? 1 : code < 0x800 ? 2 : pair ? 4 : 3

    if (size + cost > WORD_MAX) {
      out.push(word.slice(from, i))
      from = i
      size = 0
    }
    size += cost
    if (pair) i += 1
  }
  if (from < word.length) out.push(word.slice(from))
}
