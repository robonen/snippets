// ─── Реестр моделей ──────────────────────────────────────────────────────────
//
// Решение Р1 из [docs/05 §0](../../../../docs/05-model-api.md): реестр — это
// ИНТЕРФЕЙС, а поле хранит ИМЯ цели строкой (`link('user')`, а не
// `link(() => User)`).
//
// Это единственный способ выразить взаимную рекурсию `User ↔ Post` без ручного
// дублирования схемы. `keyof` интерфейса не требует резолва типов его свойств,
// поэтому `link('user')` получает автодополнение, не втягивая `typeof User`, а
// `Doc<'post'>['author']` разворачивается лениво и цикл не замыкается.
//
// Отвергнутые альтернативы — с кодами ошибок компилятора, а не по вкусу
// (docs/05 §3.13): тонк `link(() => User)` даёт каскад TS7022/TS7024 на
// константах схемы; `interface UserFields` рядом со схемой — TS2344, потому что
// у интерфейса нет неявной индексной сигнатуры, а после замены на `type`
// остаётся тот же TS7022.
//
// Цена честно записана в docs/05 §7.2: пять строк `declare module` на файл
// модели и глобальность имён. Имя лежит В ДАННЫХ и обязано быть стабильным
// вечно, поэтому переименование модели — миграция формата, а не рефакторинг.
//
// Файл держится пустым намеренно: любой импорт сюда сделал бы аугментацию
// зависимой от порядка загрузки.

/**
 * Реестр моделей приложения. В ядре пуст, расширяется слиянием объявлений.
 *
 * @example
 * ```ts
 * export const Post = model('post', {title: atom(t.string)})
 *
 * declare module '@sync/core' {
 *   interface Models {post: typeof Post}
 * }
 * ```
 */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface Models {}

/** Имя зарегистрированной модели. Чужое имя — ошибка компиляции в той же строке. */
export type ModelName = keyof Models & string
