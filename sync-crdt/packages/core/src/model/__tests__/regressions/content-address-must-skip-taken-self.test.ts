// РЕГРЕССИЯ: контентный адрес элемента обязан пропускать ЗАНЯТЫЙ живой узел.
//
// Найдено property-прогоном `text.prop.test.ts` («серия правок диапазона равна
// той же серии над обычной строкой»), сид `1838113582`, путь
// `84:1:0:0:5:5:4:4:4:4:11:10:4:8:8`, контрпример после усадки:
//
//     базовый текст  '-'
//     write('a', 0, 0)   ждали 'a-'
//     write('-', 0, 0)   ждали '-a-', получили '-a'
//
// МЕХАНИЗМ. `self` элемента — `H(соль ‖ head ‖ lead ‖ значение)`, и `lead`
// СОСЕДЕЙ при вставке не переписывается. Поэтому одна и та же пара
// (lead, значение) законно встречается дважды за жизнь списка: элемент,
// рождённый первым по адресу `H(…, ROOT, '-')`, сохраняет `lead = ROOT` и после
// того, как перед ним встал сосед. Следующая вставка того же значения в ту же
// точку считает ТОТ ЖЕ адрес — и `post` по нему не рождает второй элемент, а
// переклеивает живой первый.
//
// ПОЧЕМУ ЭТО ХУЖЕ ОБЫЧНОГО БАГА. Сходимость его не ловит: реплики теряют
// элемент СОГЛАСОВАННО, и любой тест на «две реплики читают одинаково» остаётся
// зелёным. Виден он только сверкой с эталоном — обычной строкой.
//
// ЛЕЧЕНИЕ — `address.ts`: занятый ЖИВОЙ узел пропускается перехэшированием, порт
// `self_make` из baza (`if (_self_all.has(idea)) continue`) и буквальное
// исполнение п. 32 реестра: «иначе контентный адрес может выдать занятый self и
// молча заменить чужой элемент». Надгробия при этом переиспользуются — повторный
// набор стёртого текста обязан воскрешать его юниты, а не плодить вторые.

import { describe, expect, test } from 'vitest'
import { Paper } from '../paper'
import { Shelf } from '../shelf'
import { born, stand } from '../shelf-stand'

describe('контентный адрес: занятый self пропускается', () => {
  test('усаженный контрпример на тексте', () => {
    const paper = stand().space.root(Paper)
    paper.body('-')
    paper.body.write('a', 0, 0)
    expect(paper.body()).toBe('a-')
    paper.body.write('-', 0, 0)
    expect(paper.body()).toBe('-a-')
  })

  test('тот же дефект на голом списке — тремя обычными записями', () => {
    const shelf = stand().space.root(Shelf)
    shelf.tags(['-'])
    shelf.tags(['a', '-'])
    shelf.tags(['-', 'a', '-'])
    expect(shelf.tags()).toEqual(['-', 'a', '-'])
  })

  test('вставка дубля за тем же якорем даёт второй элемент, а не тишину', () => {
    const shelf = stand().space.root(Shelf)
    shelf.tags(['a', 'b'])
    shelf.tags.insert(1, 'b')
    expect(shelf.tags()).toEqual(['a', 'b', 'b'])
  })

  test('надгробие переиспользуется: повторный набор стёртого не плодит узлы', () => {
    const at = stand()
    const shelf = at.space.root(Shelf)
    shelf.tags(['раз', 'два'])
    shelf.tags(['раз'])

    // Вернули 'два' на то же место: адрес свободен (узел мёртв), значит
    // воскрешаем прежний узел, а не заводим второй.
    const units = born(at, () => shelf.tags(['раз', 'два']))
    expect(shelf.tags()).toEqual(['раз', 'два'])
    expect(units).toBe(1)
  })

  test('схлопывание одинаковых КОНКУРЕНТНЫХ вставок не пострадало', () => {
    // Две реплики с одинаковым состоянием видят одинаковую занятость, делают
    // одинаковый пропуск и приходят к одному адресу — иначе лечение стоило бы
    // ровно того, ради чего адрес сделан контентным (docs/05 §3.6).
    const left = stand(0x11, 1000)
    const right = stand(0x22, 1000)
    left.space.root(Paper).body('общий текст')
    right.space.root(Paper).body('общий текст')

    // Считаются УЗЛЫ (`count`), а не юниты (`size`): индекс ленда хранит версии
    // по пирам, и одна и та же голова от двух пиров это законно два юнита и
    // ОДИН узел. Схлопывание — про узлы.
    const before = left.land.count()
    left.land.apply(right.land.units())
    expect(left.land.count()).toBe(before)
    expect(left.space.root(Paper).body()).toBe('общий текст')
  })
})
