// Корпус моделей для сливаемого текста.
//
// Отдельно от `blog.ts` и `shelf.ts` намеренно: `blog.ts` — сквозной пример
// docs/05 §2 и предмет тестов ТИПОВ, а рантайм-тесты обязаны работать на том,
// что собрано. Здесь ровно два текстовых поля и атом рядом с ними — атом нужен,
// чтобы проверить, что появление СОСЕДНЕГО поля не задевает текст.

import { atom, model, t, text } from '../index'

export const Paper = model('paper', {
  title: atom(t.string),
  /** Основной предмет: абзацы, внутри токены. */
  body: text(),
  /** Второй текст в том же документе: у полей общая голова и разные слоты. */
  note: text(),
})

declare module '../registry' {
  interface Models {
    paper: typeof Paper
  }
}
