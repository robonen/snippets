// ─── Чем вложенная часть держится за родителя ────────────────────────────────
//
// `part('stats')` обязан выполнить два обещания сразу, и они тянут в разные
// стороны (docs/05 §1.3):
//
//   «есть всегда»           — `post.stats()` возвращает `Doc`, а не `Doc | null`,
//                             и потому не имеет права ничего создавать: чтение
//                             не пишет юнитов НИКОГДА (docs/05 §2.5);
//   «живёт в поддереве»     — счётчики умирают вместе с постом, значит ключевой
//                             юнит `stats` обязан быть РЕБЁНКОМ головы поста,
//                             иначе `$.drop()`, `$.changedAt()` и `$.authors()`
//                             его не видят.
//
// Развязка: адрес части считается ЗАРАНЕЕ и детерминированно — `predictKey`
// даёт ровно тот `self`, который позже запишет `mountSlot`, — поэтому чтение
// возвращает документ по будущему адресу, ничего не записав. А сам ключевой
// юнит материализуется ПЕРВОЙ ЗАПИСЬЮ внутрь части: `post.stats().views(1)`
// идёт через `mountSlot` под головой части, и вот там цепочка родителей и
// достраивается — снизу вверх, по одной записи на уровень.
//
// Без этого «часть живёт в поддереве родителя» было бы неправдой: юниты
// `views`/`likes` висели бы на узле, которого нет ни у одной головы в детях, и
// `post.$.drop()` оставлял бы их сиротами навсегда.
//
// ПОЧЕМУ карта, а не поле в ячейке. Ячейка живёт на (модель × поле), а вложенность
// — на (голова части → голова родителя): у одной ячейки `stats` столько
// родителей, сколько постов прочитали. Класть это в ячейку значило бы завести в
// ней вторую карту по голове, то есть ту же карту, но в неудобном месте.

import { predictKey } from './address'
import type { Head } from './channel'
import { type Cell, mountSlot } from './cell'
import type { Field } from './field'
import { ROOT } from '../land/view'
import type { SpaceCore } from './space'

/** Родитель вложенной головы: где её ключевой юнит должен появиться. */
interface Nest {
  readonly head: Head
  readonly key: string
  readonly field: Field
}

/**
 * Голова части → её родитель.
 *
 * `WeakMap` по ядру: вложенности живут ровно столько же, сколько пространство, и
 * освобождаются вместе с ним одним движением.
 */
const nests = new WeakMap<SpaceCore, Map<Head, Nest>>()

/**
 * Слот вложенного документа: реальный, если он уже есть, иначе — предсказанный.
 *
 * Не пишет НИ ОДНОГО юнита. Побочный эффект здесь ровно один — запись в карту
 * вложенностей, и она идемпотентна, не читает сигналов и не бьёт их, поэтому
 * вызов из тела `computed` безопасен: пересчёт даст ту же запись.
 *
 * Реактивность берётся у `cell.slot` — канала «где лежит» из решения Р3, а не
 * прямым чтением `keyIndex`: два кэша на один состав детей дали бы два ответа на
 * один вопрос.
 */
export function nestSlot(core: SpaceCore, cell: Cell, head: Head): Head {
  const found = cell.slot(head)
  if (found !== ROOT) return found

  // Тот же адрес, который запишет `mountSlot`: формула одна на оба пути, иначе
  // «прочитали до записи» и «прочитали после» дали бы разные документы.
  const self = predictKey(core.land, core.salt, head, cell.key)
  remember(core, self, head, cell.key, cell.field)
  return self
}

/**
 * Достроить цепочку родителей до этой головы. Идемпотентно.
 *
 * Зовётся из {@link mountSlot}, то есть с КАЖДОЙ первой записи в поле. Рекурсия
 * идёт строго вверх и обрывается на голове, которая ни у кого не в детях, —
 * глубина равна глубине вложенности схемы, а не размеру данных.
 */
export function mountNest(core: SpaceCore, head: Head): void {
  const map = nests.get(core)
  if (map === undefined) return
  const nest = map.get(head)
  if (nest === undefined) return
  // `mountSlot` сам позовёт `mountNest` для СВОЕЙ головы — так собирается вся
  // цепочка, а повторный проход по уже смонтированному уровню стоит один
  // `Map.get` в `keyIndex`.
  mountSlot(core, nest.head, nest.key, nest.field)
}

function remember(core: SpaceCore, self: Head, head: Head, key: string, field: Field): void {
  let map = nests.get(core)
  if (map === undefined) {
    map = new Map()
    nests.set(core, map)
  }
  if (!map.has(self)) map.set(self, { head, key, field })
}
