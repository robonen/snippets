import { describe, expect, test } from 'vitest'
import { computed, watchEffect } from './computed'
import { flush } from './graph'

/**
 * Именованная регрессия: подметание карты ключей обязано быть амортизированно
 * O(1), а не O(числа живых ключей).
 *
 * ЧТО БЫЛО. `computed.keyed` подметал осиротевшие узлы «раз в сотню промахов», а
 * подметание — это обход ВСЕЙ карты. На `n` новых ключах суммарная работа
 * выходила O(n²/100), и комментарий рядом обещал ровно обратное. Дефект
 * невидим, пока ключей десятки: он вылез на первом потребителе, у которого ключ
 * — это документ, то есть на слое моделей S4.
 *
 * ЦИФРЫ (Node 24, `packages/core/bench/model.mjs` и отдельный прогон):
 *
 * | живых ключей | цена промаха ДО | ПОСЛЕ |
 * |--------------|-----------------|-------|
 * | 1 000        | 325 нс          | 311 нс |
 * | 20 000       | 869 нс          | 170 нс |
 * | 50 000       | 1705 нс         | 162 нс |
 *
 * Холодное чтение поля модели, где промахов пять, — 2.06 → 44.6 мкс на
 * пятидесяти тысячах документов; после правки 2.06 → 2.4 мкс.
 *
 * ПОЧЕМУ ТЕСТ ВРЕМЕННОЙ. Подметание не наблюдаемо через API: оно ничего не
 * возвращает и ничего не зовёт. Наблюдаема только его цена, поэтому порог взят с
 * большим запасом — дефект давал ×5.2 на этом диапазоне, исправленный код даёт
 * около ×1, порог ×3. Тест меряет ОТНОШЕНИЕ двух прогонов в одном процессе,
 * поэтому не зависит ни от машины, ни от её загрузки в абсолютных числах.
 */
describe('регрессия: computed.keyed подметает амортизированно', () => {
  const SMALL = 2_000
  const LARGE = 50_000

  function perMiss(count: number): number {
    const channel = computed.keyed((key: number) => key + 1)
    // Прогрев отдельным каналом того же вида: JIT не должен попасть в замер.
    const warm = computed.keyed((key: number) => key + 1)
    for (let i = 0; i < 1_000; i++) warm(i)

    const start = process.hrtime.bigint()
    for (let i = 0; i < count; i++) channel(i)
    return Number(process.hrtime.bigint() - start) / count
  }

  test('цена промаха не растёт с числом живых ключей', () => {
    const small = perMiss(SMALL)
    const large = perMiss(LARGE)

    expect(large / small).toBeLessThan(3)
  })

  test('уборка всё ещё происходит: сирота исчезает при росте карты', () => {
    const channel = computed.keyed((key: number) => key + 1)
    const stop = watchEffect(() => {
      channel(0)
    })
    expect(channel.size).toBe(1)

    // Наблюдатель отвернулся — узел собран графом, но запись в карте осталась.
    stop()
    flush()

    // Карта растёт свежими ключами и на первом же водоразделе подметается.
    for (let i = 1; i <= 200; i++) channel(i)
    expect(channel.size).toBeLessThanOrEqual(200)
  })
})
