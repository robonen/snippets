// Общий журнал бюджетов и сторож регресса.
//
// PRINCIPLES.md, «Гейт производительности»: «Бюджеты лежат в `bench/budgets.json`
// и проверяются в CI. Регресс > 10 % — красный билд, а не „потом посмотрим"».
//
// Первая редакция этого файла обещание НЕ ИСПОЛНЯЛА: она только перезаписывала
// журнал, ни разу с ним не сравнив, — то есть каждый прогон стирал базу, с
// которой полагалось сравнивать. Обещание держалось на том, что кто-то откроет
// diff глазами. Это тот же класс дефекта, что молчаливый пропуск браузерного
// раздела: гейт есть, красным не становится никогда.
//
// ─── Что считается регрессом ─────────────────────────────────────────────────
//
// Сравниваются числовые поля с известным смыслом: `*_ns`, `*_ms`, `*_bytes`,
// `measured_ns`, `avg_ns` и подобные — то есть «меньше значит лучше». Поля вроде
// `limit_ns` (это обещание, а не замер) и `passed` пропускаются.
//
// Порог — 10 %, и он односторонний: ускорение это не регресс. Шум меньше порога
// не трогаем намеренно, иначе сторож будет краснеть на каждом прогоне и его
// перестанут читать — ровно та же болезнь, от которой лечим.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const file = join(dirname(fileURLToPath(import.meta.url)), 'budgets.json')

/**
 * Насколько замер вправе ухудшиться, прежде чем это станет красным.
 *
 * ЧИСЛО ВЫВЕДЕНО ЗАМЕРОМ ШУМА, а не взято из обещания. PRINCIPLES.md называет
 * 10 %, но пять прогонов НЕИЗМЕННОГО кода дали размах до **×1.35** (худший —
 * `encode/blob-32k`: 2965 → 4003 нс; у большинства сценариев ×1.03–1.12).
 * Порог ниже собственного шума машины делает сторожа генератором ложных тревог,
 * а сторож, которому не верят, не ловит уже ничего.
 *
 * Отсюда разделение труда двух сетей, и оно намеренное:
 * — АБСОЛЮТНЫЕ БЮДЖЕТЫ (в каждом гейте свои) — сеть частая: они проверяют, что
 *   код укладывается в обещанное, и шум им не мешает, потому что запас к бюджету
 *   обычно кратный;
 * — ЭТОТ СТОРОЖ — сеть редкая: он ловит то, что бюджет пропустил, потому что
 *   запас позволил, — «стало вдвое хуже, но всё ещё под бюджетом».
 *
 * Обещание в PRINCIPLES.md исправлено по этому замеру.
 */
const REGRESSION = 1.4

/**
 * Что сторож НЕ сравнивает. Всё остальное числовое — сравнивает.
 *
 * ПОЧЕМУ ЧЁРНЫЙ СПИСОК, А НЕ БЕЛЫЙ. Первая редакция перечисляла, что брать
 * (`_ns`, `_ms`, `avg`…), и дважды молча роняла целые гейты: сначала весь слой
 * моделей, потому что он кладёт главное число под именем `measured`, потом
 * хранилище — `stored_over_live`, `grew`, `over_floor`, `per_unit_us`. Белый
 * список ошибается В СТОРОНУ МОЛЧАНИЯ: незнакомое имя просто не сторожится, и
 * узнать об этом можно только перечитав сам сторож.
 *
 * Чёрный список ошибается в другую сторону — незнакомое имя попадает под
 * надзор. Худшее, что бывает, — ложная тревога, которую видно и можно погасить
 * одной строкой здесь. Это ровно то правило, ради которого сторож и написан:
 * проверка, которая может молча не сработать, хуже её отсутствия.
 */
const SKIP = [
  /** Обещания: это и есть бюджет, сравнивать его с собой бессмысленно. */
  /^(limit|budget|note|why|spec|was|target)/,
  /** Хвостовая статистика: гуляет вдвое на неизменном коде. */
  /^p99/,
  /** Служебное: версии, отметки времени, счётчики прогонов. */
  /^(node|platform|measuredAt|runs|count|seed|version)$/,
]

/** Плоский обход: `a.b.c` → число. Возвращает карту «путь → значение». */
function flatten(value, prefix = '', out = new Map()) {
  if (value === null || typeof value !== 'object') return out
  for (const [key, item] of Object.entries(value)) {
    const path = prefix === '' ? key : `${prefix}.${key}`
    if (SKIP.some(rule => rule.test(key))) continue
    if (typeof item === 'number') {
      // Ноль и отрицательные не сторожатся: отношение к ним не определено, а
      // отрицательный замер — сам по себе дефект инструмента, и ловить его
      // должен гейт, а не сторож.
      if (Number.isFinite(item) && item > 0) out.set(path, item)
      continue
    }
    if (typeof item === 'boolean' || typeof item === 'string') continue
    flatten(item, path, out)
  }
  return out
}

/**
 * Записать раздел журнала и сравнить его с предыдущим.
 *
 * Возвращает список регрессов; печатает их сам. Прогон не роняет — решение
 * ронять принимает вызывающий гейт, у него больше контекста.
 */
export function record(section, data) {
  const current = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {}

  // Пропущенный прогон НЕ затирает измеренное.
  //
  // Раздел, снятый только в браузере, на машине без браузера писался заглушкой
  // `{skipped: true, passed: true}` — и вместе с ней исчезали настоящие числа,
  // то есть база, с которой полагалось сравнивать. Один прогон в неудачной среде
  // стирал историю, и сторож регресса на следующем прогоне сравнивать было не с
  // чем: он молчал, потому что не с чем, а выглядело это как «всё хорошо».
  //
  // Поэтому пропуск ДОПИСЫВАЕТСЯ к тому, что уже измерено, а не заменяет его.
  const kept = current[section]
  if (data.skipped === true && kept !== undefined && kept.skipped !== true) {
    writeFileSync(file, `${JSON.stringify({
      ...current,
      [section]: { ...kept, lastSkipped: { why: data.why ?? null, node: process.version } },
    }, null, 2)}\n`)
    console.log(`\n→ bench/budgets.json: раздел «${section}» ПРОПУЩЕН, прежние числа сохранены`)
    return []
  }

  const before = flatten(current[section])
  const after = flatten(data)

  const worse = []
  for (const [path, now] of after) {
    const was = before.get(path)
    if (was === undefined) continue
    const ratio = now / was
    if (ratio > REGRESSION) worse.push({ path, was, now, ratio: Math.round(ratio * 100) / 100 })
  }

  const next = {
    ...current,
    measuredAt: new Date().toISOString(),
    node: process.version,
    platform: `${process.platform}/${process.arch}`,
    note: 'База для сравнения. Регресс > 10 % — красный билд (PRINCIPLES.md, правило 2).',
    [section]: data,
  }

  writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`)
  console.log(`\n→ bench/budgets.json: раздел «${section}»`)

  if (worse.length > 0) {
    worse.sort((a, b) => b.ratio - a.ratio)
    console.log(`  ✗ РЕГРЕСС против прошлого прогона (порог ${Math.round((REGRESSION - 1) * 100)} %):`)
    for (const item of worse) {
      console.log(`     ${item.path.padEnd(38)} ${item.was} → ${item.now}  (×${item.ratio})`)
    }
    process.exitCode = 1
  }

  return worse
}
