<script setup lang="ts">
import { TooltipProvider } from '@robonen/primitives';

/**
 * Общая настройка всех подсказок приложения. Монтируется один раз в оболочке,
 * вокруг всего дерева.
 *
 * Провайдер обязателен: без него {@link Tooltip} бросит исключение при
 * монтировании. Ставить по провайдеру на каждую подсказку было бы соблазнительно
 * и неверно — именно общий провайдер помнит, что подсказку только что закрыли,
 * и следующую в той же панели показывает без повторной паузы. С отдельными
 * провайдерами каждая иконка снова ждала бы 700 мс.
 */
defineProps<{
  /** Пауза перед показом, мс. */
  delay?: number;
  /** Окно, в котором соседние подсказки открываются сразу, мс. */
  skipDelay?: number;
}>();
</script>

<template>
  <TooltipProvider :delay-duration="delay ?? 500" :skip-delay-duration="skipDelay ?? 300">
    <slot />
  </TooltipProvider>
</template>
