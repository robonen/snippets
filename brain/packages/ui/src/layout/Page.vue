<script setup lang="ts">
import { computed } from 'vue';

/**
 * Рама экрана: мера строки, поля и правый рельс.
 *
 * Заведена вместо одиннадцати самостоятельных `mx-auto max-w-2xl`. Дело не в
 * повторе класса, а в том, что 42 rem — мера для ЧТЕНИЯ, и на десктопе она
 * оставляла колонку висеть посреди полутора тысяч пикселей пустоты. Ширина
 * должна следовать из того, что на экране, а не быть одной на всё:
 *
 * - `reading` — текст. Ограничение сверху существует ради глаза: строка длиннее
 *   ~75 знаков теряется на возврате, и растягивать её на весь монитор нельзя,
 *   сколько бы места ни было.
 * - `list` — списки и формы. Строке нужно место под значение справа и действия,
 *   но бесконечная ширина превращает список в таблицу без заголовков.
 * - `wide` — сводки, графики, бенто. Здесь ширина работает: чем больше колонок,
 *   тем меньше прокрутки.
 *
 * Правый рельс (`aside`) включается по КОНТЕЙНЕРНОМУ запросу, а не по ширине
 * окна, и это не педантизм. Внутри мастер-деталя колонка содержимого уже на
 * ширину списка уже окна: при `xl:` на мониторе 1300 px рельс включался, а
 * тексту оставалось 320 px — вдвое меньше меры чтения. Страница обязана
 * смотреть на СВОЮ ширину, потому что только она и определяет, поместятся ли
 * две колонки.
 */
const { width = 'list', gutter = true } = defineProps<{
  width?: 'reading' | 'list' | 'wide' | 'full';
  /** Боковые поля. Выключаются там, где экран сам рисует полноширинные полосы. */
  gutter?: boolean;
}>();

const MEASURES: Record<NonNullable<typeof width>, string> = {
  reading: 'max-w-[46rem]',
  list: 'max-w-[64rem]',
  wide: 'max-w-[84rem]',
  full: '',
};

const measure = computed(() => MEASURES[width]);
</script>

<template>
  <div
    class="@container mx-auto w-full"
    :class="[measure, gutter && 'px-4 py-6 sm:px-6 lg:px-8']"
  >
    <div
      v-if="$slots.aside"
      class="grid gap-8 @[58rem]:grid-cols-[minmax(0,1fr)_18rem]"
    >
      <div class="min-w-0">
        <slot />
      </div>
      <!-- Липкий рельс: при длинном тексте он обязан оставаться на виду, иначе
           это просто подвал, до которого никто не доскроллит. -->
      <aside class="min-w-0 @[58rem]:sticky @[58rem]:top-6 @[58rem]:self-start">
        <slot name="aside" />
      </aside>
    </div>

    <slot v-else />
  </div>
</template>
