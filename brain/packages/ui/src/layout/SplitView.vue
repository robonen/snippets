<script setup lang="ts">
/**
 * Мастер-деталь: список слева, открытое — справа.
 *
 * Раскладка настольного приложения, а не растянутая мобильная. Узкая колонка
 * по центру экрана шириной в полторы тысячи пикселей — это признание, что
 * ширина некуда девать; на самом деле деть её есть куда: список остаётся
 * открытым рядом с содержимым, и переход между записями перестаёт быть
 * навигацией «туда-обратно».
 *
 * Ниже `lg` слоты НЕ ужимаются в две узкие колонки, а показываются по одному:
 * какой именно — решает вызывающий (обычно по наличию выбранной записи), и
 * это его работа, потому что только он знает, что считается «открыто».
 */
const { showDetail = true } = defineProps<{
  /** На узком экране: показать содержимое (иначе — список). */
  showDetail?: boolean;
  /** Ширина колонки списка на десктопе. */
  railWidth?: string;
}>();
</script>

<template>
  <div
    class="grid min-h-[calc(100dvh-1px)] lg:grid-cols-[var(--rail)_minmax(0,1fr)]"
    :style="{ '--rail': railWidth ?? '21rem' }"
  >
    <!-- Колонка списка прокручивается сама: длинный список не должен утаскивать
         вниз открытую запись, и наоборот. -->
    <div
      class="min-w-0 border-line lg:sticky lg:top-0 lg:h-dvh lg:overflow-y-auto lg:border-r"
      :class="showDetail && 'hidden lg:block'"
    >
      <slot name="list" />
    </div>

    <div class="min-w-0" :class="!showDetail && 'hidden lg:block'">
      <slot name="detail" />
    </div>
  </div>
</template>
