import { computed, effectScope } from 'vue';
import { useColorMode } from '@robonen/vue';
import type { ComputedRef } from 'vue';

/**
 * Тема: система, светлая или тёмная.
 *
 * «Система» — не третье оформление, а ОТСУТСТВИЕ выбора: дальше решает
 * `prefers-color-scheme`. Поэтому состояние здесь — именно выбор пользователя,
 * а не вычисленная тема; хранить вычисленную значило бы заморозить её и
 * перестать следовать за системой.
 *
 * Под капотом — `useColorMode` из `@robonen/vue`. Своя реализация была на
 * десяток строк короче ровно до тех пор, пока не начинала быть правильной:
 * чтение хранилища в try/catch, синхронизация между вкладками через событие
 * `storage`, подписка на смену системной темы и гашение переходов на время
 * переключения. Последнее заметно глазом: без него смена темы протаскивает
 * КАЖДЫЙ `transition-colors` на странице, и вместо мгновенной перекраски
 * получается волна на четверть секунды.
 */
export type ThemeChoice = 'system' | 'light' | 'dark';

/**
 * Ключ остался прежним, и это не мелочь: у тех, кто уже выбрал тёмную, в
 * хранилище лежит `'dark'` по этому имени. Новый ключ означал бы, что при
 * первом же запуске после обновления их выбор молча сбросился на системный.
 */
const STORAGE_KEY = 'brain.theme';

/**
 * Внутри композабл называет «системное» значение `'auto'`, наружу кит отдаёт
 * `'system'`. Разъезд имён не стоит того, чтобы протекать в модули и в
 * сохранённый выбор, поэтому перевод живёт здесь — в одном месте и в обе
 * стороны.
 */
const AUTO = 'auto';

/**
 * Тема — одна на приложение, поэтому и состояние одно. Создаётся лениво, а не
 * на импорте: обращение к `localStorage` и к `matchMedia` в момент разбора
 * модуля падает там, где документа ещё нет.
 */
let shared: {
  choice: ComputedRef<ThemeChoice>;
  set: (next: ThemeChoice) => void;
} | undefined;

function theme(): NonNullable<typeof shared> {
  if (shared !== undefined) return shared;

  /*
   * Отдельная область видимости, и она несущая по двум причинам.
   *
   * Если первым тему спросит КОМПОНЕНТ, наблюдатели внутри `useColorMode`
   * достанутся его области и снимутся на размонтировании — общая тема молча
   * перестанет следовать за системной. В консоли об этом не скажут.
   *
   * Предупреждение «onMounted is called when there is no active component
   * instance» областью НЕ лечится и остаётся: `onMounted` смотрит на экземпляр
   * компонента, а его при вызове из `main.ts` нет и быть не должно — тема
   * обязана встать до первой отрисовки. Предупреждение только для разработки.
   */
  effectScope(true).run(() => {
    const mode = useColorMode({
      storageKey: STORAGE_KEY,
      // Атрибут, а не класс: тема в токенах живёт на `:root[data-theme]`, и
      // класс потребовал бы переписать половину `tokens.css` ради того же.
      attribute: 'data-theme',
      // Без этого чтение отдавало бы ВЫЧИСЛЕННУЮ тему, и переключатель на
      // «системе» подсвечивал бы «светлую» — то есть врал бы о выборе.
      emitAuto: true,
    });

    shared = {
      choice: computed<ThemeChoice>(() => (mode.value === AUTO ? 'system' : mode.value)),
      set(next) {
        mode.value = next === 'system' ? AUTO : next;
      },
    };
  });

  return shared!;
}

export function useTheme(): {
  choice: ComputedRef<ThemeChoice>;
  set: (next: ThemeChoice) => void;
} {
  return theme();
}

/**
 * Применить тему ДО отрисовки — в `main.ts`, не в компоненте: атрибут,
 * поставленный после монтирования, даёт вспышку светлой темы у того, кто
 * выбрал тёмную.
 *
 * Работает потому, что первый проход наблюдателя внутри `useColorMode`
 * синхронный: к возврату из этой функции `data-theme` на `<html>` уже стоит.
 */
export function initTheme(): void {
  theme();
}
