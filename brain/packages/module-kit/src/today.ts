import { computed, effectScope } from 'vue';
import { useNow } from '@robonen/vue';
import { toISODate } from '@brain/std';
import type { ComputedRef } from 'vue';

/**
 * Сегодняшняя дата, которая переживает полночь.
 *
 * `todayISO()` в setup выглядит безобидно и врёт ровно один раз в сутки — но
 * приложение этого класса держат открытым: закреплённая вкладка, PWA на
 * телефоне. После полуночи вчерашние задачи оставались в корзине «Сегодня»,
 * ссылка на заметку дня вела во вчера, а быстрый ввод разбирал «завтра»
 * относительно вчера — то есть молча ставил срок не на тот день.
 *
 * Тик раз в минуту, а не таймер на полночь: последний не переживает сон машины,
 * минутный сам догоняет при пробуждении. На зависимых `computed` это не
 * сказывается — значение строковое, Vue сравнивает результат, и одинаковая дата
 * никого не будит: пересчёт раз в сутки, а не раз в минуту.
 */
let shared: ComputedRef<string> | undefined;

export function useToday(): ComputedRef<string> {
  if (shared === undefined) {
    /*
     * Отдельная область видимости, и это не перестраховка: `useNow` вешает
     * остановку таймера на текущий scope. Без detached-области часы достались
     * бы ПЕРВОМУ спросившему компоненту и встали бы на его размонтировании —
     * у всех остальных дата застыла бы молча.
     *
     * Одни часы на приложение: `useNow` в каждом экране завёл бы столько
     * таймеров, сколько их открыто, ради одного и того же числа.
     */
    effectScope(true).run(() => {
      const now = useNow({ interval: 60_000 });
      shared = computed(() => toISODate(now.value));
    });
  }
  return shared!;
}
