/** Слов во фразе. Двенадцать по 8 бит — 96 бит энтропии. */
export const PHRASE_LENGTH = 12;

/**
 * Словарь для сверки — один на модуль, а не новый Set на каждую проверку: ввод
 * фразы сверяется по слову за набором, и 256 записей на каждое нажатие ни к чему.
 *
 * «ё» складывается в «е» той же рукой, что и в {@link normalizePhrase}: сейчас в
 * словаре «ё» нет по построению, но сверка и запись обязаны сходиться и дальше.
 */
const DICTIONARY = new Set(WORDS.map(word => word.replaceAll('ё', 'е')));

/**
 * Сгенерировать фразу. Показывается ровно один раз и больше нигде не хранится:
 * записанная в приложение, она перестала бы быть вторым фактором.
 */
export function createPhrase(length: number = PHRASE_LENGTH): string[] {
  if (WORDS.length !== 256) {
    throw new Error(`словарь обязан быть ровно 256 слов, а в нём ${WORDS.length}: иначе выборка неравномерна`);
  }
  const source = randomBytes(length);
  return [...source].map(byte => WORDS[byte]!);
}

/** Каноническая запись: нижний регистр, одиночные пробелы, без хвостов. */
export function normalizePhrase(phrase: string | readonly string[]): string {
  const words = typeof phrase === 'string' ? phrase.split(/\s+/u) : phrase;
  return words
    .map(word => word.trim().toLowerCase().replaceAll('ё', 'е'))
    .filter(word => word !== '')
    .join(' ');
}

/**
 * Проверить, что фраза вообще может быть нашей, ДО дорогого KDF: иначе опечатка
 * стоила бы пользователю секунды ожидания и ответа «не подошло».
 */
export function isKnownPhrase(phrase: string | readonly string[], length: number = PHRASE_LENGTH): boolean {
  const words = normalizePhrase(phrase).split(' ');
  if (words.length !== length) return false;
  return words.every(word => DICTIONARY.has(word));
}

/**
 * Задание на проверку записи: индексы слов, которые попросят ввести.
 *
 * Без этого шага «я записал фразу» остаётся непроверенным утверждением, а цена
 * ошибки — все данные.
 */
export function quizIndexes(count = 2, length: number = PHRASE_LENGTH): number[] {
  const picked = new Set<number>();
  // Отбраковка вместо остатка от деления: 256 не делится на 12 нацело, и `%`
  // сделал бы первые индексы чаще прочих. Здесь это косметика, но привычка
  // брать остаток от случайного байта — ровно та, что портит ключи.
  const limit = Math.floor(256 / length) * length;
  while (picked.size < Math.min(count, length)) {
    const byte = randomBytes(1)[0]!;
    if (byte < limit) picked.add(byte % length);
  }
  return [...picked].sort((a, b) => a - b);
}
