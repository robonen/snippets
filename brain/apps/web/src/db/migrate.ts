import type { Space } from '@sync/core';
import { MetaModel, readInbox, writeInbox } from './meta';
import type { InboxItem } from './meta';

/**
 * Переезд инбокса из мета-ленда в свой.
 *
 * Мета-ленд лежит на диске ОТКРЫТЫМ — иначе обёртки ключа было бы нечем
 * прочитать до появления ключа. Пойманные мысли и ссылки открытыми лежать не
 * должны, поэтому они уезжают в собственный ленд, который шифруется наравне с
 * модульными (docs/01-security.md §4).
 *
 * Идемпотентно: записи переносятся по своим же идентификаторам, повторный
 * прогон перепишет их теми же значениями. Обрыв между переносом и очисткой
 * оставляет их в обоих местах, и следующий запуск доделает — обратный порядок
 * терял бы их совсем.
 */
export function moveInbox(meta: Space, inbox: Space): number {
  const from = meta.root(MetaModel);
  const ids = from.inbox.keys();
  if (ids.length === 0) return 0;

  // Снимок до записи: дальше эти же записи будут затираться, и читать их по
  // ходу дела значило бы зависеть от порядка обхода.
  const items: InboxItem[] = ids.map(id => readInbox(id, from.inbox(id)));

  const to = inbox.root(MetaModel);
  inbox.edit(() => {
    for (const item of items) writeInbox(to.inbox(item.id), item);
  });

  meta.edit(() => {
    for (const item of items) {
      /*
       * Сначала ЗАТЕРЕТЬ, потом удалить, и порядок здесь несущий.
       *
       * `delete` кладёт надгробие на ключевой юнит записи, но её дети — атомы с
       * текстом, ссылкой и источником — остаются в ленде: образ хранилища
       * замещает юнит ПО КЛЮЧУ, а не по поддереву, и до чужих ключей ему дела
       * нет. То есть одного удаления мало: пойманная мысль осталась бы лежать
       * открытым текстом в мета-ленде навсегда.
       *
       * Пустая строка поверх текста — это новая версия ТОГО ЖЕ атома, и она
       * перезаписывает его байты в образе (а изменившая длину — ещё и зануляет
       * прежний слот). Только после этого удаление ключа безопасно.
       */
      writeInbox(from.inbox(item.id), { id: item.id, text: '', source: '', createdAt: 0 });
    }
  });
  for (const item of items) from.inbox.delete(item.id);

  return items.length;
}
