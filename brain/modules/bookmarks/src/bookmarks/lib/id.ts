/**
 * Идентификатор новой закладки.
 *
 * UUID, а не счётчик: ключ каталога рождается на устройстве, которое про
 * остальные ничего не знает, и «следующий номер» на двух устройствах сразу дал
 * бы одну закладку поверх другой при первом же слиянии.
 */
export function newId(): string {
  return crypto.randomUUID();
}
