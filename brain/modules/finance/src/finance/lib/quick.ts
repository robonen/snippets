import { matchAmount } from './money';

/**
 * Быстрый ввод траты одной строкой: «250 кофе» → 25000 копеек и «кофе».
 *
 * Главный вход модуля: трата записывается за то же время, за какое её обычно
 * забывают записать. Поэтому разбор — чистая функция, а не метод формы: та же
 * строка приезжает из инбокса и из команды палитры, а форма — лишь один из
 * входов.
 */

/**
 * Сумма читается только в НАЧАЛЕ строки. Обратный порядок («кофе 250») выглядит
 * заманчиво, но делает разбор гадательным: в «маршрутка 2» двойка — это два
 * рубля или номер маршрута? Одно правило, о котором можно рассказать в
 * подсказке, честнее двух правил с исключениями.
 */

/** Знак валюты сразу за суммой: «250 ₽ кофе». Это не описание — его съедаем. */
const CURRENCY = /^\s*(?:₽|руб\.?|р\.?)(?=\s|$)/i;

/** Пачки пробелов внутри описания. */
const SPACES = /\s+/g;

/** Разобранная строка быстрого ввода. */
export interface QuickEntry {
  /** Сумма в копейках, целое и строго больше нуля. */
  readonly amount: number;
  /** Остаток строки как описание. Пустая строка — сумму ввели без пояснения. */
  readonly note: string;
}

/**
 * Разобрать строку быстрого ввода. `null` — записывать нечего: суммы нет, она
 * нулевая или строка начинается не с числа.
 *
 * Знак не принимается намеренно: у траты его не бывает, а «-250» — это либо
 * маркер списка, либо опечатка, и молча превратить его в расход значило бы
 * записать не то, что ввели.
 */
export function parseQuickEntry(input: string): QuickEntry | null {
  const trimmed = input.trim();
  const match = matchAmount(trimmed);
  if (match === null) return null;
  // Трата на ноль — это не трата: строка «0 кофе» почти всегда недонабрана.
  if (match.amount === 0) return null;

  const note = trimmed
    .slice(match.end)
    .replace(CURRENCY, '')
    .trim()
    .replaceAll(SPACES, ' ');

  return { amount: match.amount, note };
}
