/**
 * Идентификатор новой траты или категории.
 *
 * UUID, а не счётчик: ключ каталога рождается на устройстве, которое про
 * остальные ничего не знает, и «следующий номер» на телефоне и на ноутбуке
 * совпал бы — одна трата легла бы поверх другой при первом же слиянии.
 */
export function newId(): string {
  return crypto.randomUUID();
}
