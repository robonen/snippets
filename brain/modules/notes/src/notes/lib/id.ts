/**
 * Ключ новой заметки.
 *
 * UUID, а не счётчик: id — это ключ документа в ленде, и два устройства,
 * писавшие оффлайн, обязаны разойтись ключами. Счётчик дал бы им одинаковый
 * «note-4», и слияние склеило бы две разные заметки в одну.
 *
 * Заметка дня — сознательное исключение: её ключ чеканится из даты ровно ради
 * обратного эффекта (см. `db/actions.ts`).
 */
export function newId(): string {
  return crypto.randomUUID();
}
