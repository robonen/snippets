import type { Note } from './note';

/**
 * Теги как первоклассная сущность: свой словаря у них нет и не нужно.
 *
 * Список тегов ВЫВОДИТСЯ из заметок, а не хранится отдельным каталогом.
 * Отдельный каталог пришлось бы держать согласованным при каждой правке любой
 * заметки — и первым же расхождением стал бы тег, который есть в справочнике и
 * ни на одной заметке. Цена вывода — обход коллекции на каждый показ; заметок у
 * одного человека тысячи, а не миллионы.
 */

export interface TagCount {
  readonly tag: string;
  readonly count: number;
}

/**
 * Теги с числом заметок, по убыванию частоты.
 *
 * Частота, а не алфавит: список тегов читают, чтобы выбрать фильтр, и сверху
 * должно стоять то, чем человек пользуется, а не то, что начинается на «а».
 * Одинаково частые разводятся алфавитом — иначе порядок зависел бы от того,
 * чей юнит приехал первым.
 */
export function countTags(notes: readonly Note[]): TagCount[] {
  const counts = new Map<string, number>();
  for (const note of notes) {
    for (const [index, tag] of note.tags.entries()) {
      // Считаются ЗАМЕТКИ, а не вхождения: свой парсер повторов не отдаёт, но
      // снимок приезжает и с другого устройства, а «12 заметок» обязано быть
      // правдой в любом случае.
      if (note.tags.indexOf(tag) !== index) continue;
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    }
  }

  return [...counts]
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => (b.count - a.count) || a.tag.localeCompare(b.tag, 'ru'));
}

/**
 * Сколько заметок у тега; ноль — если такого тега уже нет ни на одной.
 *
 * Ноль случается не в теории: выбранный в фильтре тег живёт на экране, а
 * последняя заметка с ним могла уехать в архив из соседней вкладки.
 */
export function countOf(counts: readonly TagCount[], tag: string): number {
  return counts.find(item => item.tag === tag)?.count ?? 0;
}
