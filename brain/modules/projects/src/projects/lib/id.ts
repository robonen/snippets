/**
 * Идентификатор проекта и его строк (участник, оплата, ссылка, запись).
 *
 * UUID, а не счётчик: ключ рождается на устройстве, которое про остальные
 * ничего не знает, и «следующий номер» на двух устройствах сразу положил бы
 * одну запись поверх другой при первом же слиянии.
 */
export function newId(): string {
  return crypto.randomUUID();
}
